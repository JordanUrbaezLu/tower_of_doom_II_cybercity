    local function burst( cx, cy, col, reach, n )
        for i = 1, math.min( n, #fx.shards ) do
            local e = fx.shards[ i ]
            local a = ( i - 1 ) * 2 * math.pi / n
            e:completeAnimation()
            e:setRGB( col[ 1 ], col[ 2 ], col[ 3 ] )
            e:setZRot( math.deg( a ) )
            e:setLeftRight( true, false, cx - 7, cx + 7 )
            e:setTopBottom( true, false, cy - 7, cy + 7 )
            e:setAlpha( 1 )
            e:beginAnimation( "tod_spin_shard", 360, false, false, CoD.TweenType.Linear )
            e:setLeftRight( true, false, cx + math.cos( a ) * reach - 5, cx + math.cos( a ) * reach + 5 )
            e:setTopBottom( true, false, cy + math.sin( a ) * reach - 5, cy + math.sin( a ) * reach + 5 )
            e:setAlpha( 0 )
        end
    end

