    end

    -- the window is k-4 .. k+4: exactly SLOTS tiles. A step k moves the strip from k-1 to k (STOPPED SHORT runs on
    -- to k + 0.44), so k-4 is the left tile at the step's start and k+4 the sliver at the hang's right edge. It ran
    -- to k+5 until 2026-10-02: ten tiles into nine slots, so k+5 took k-4's slot and the left tile vanished at the
    -- start of every step (unseen at speed; a SLIPPED PAST creep held that gap on screen for most of a second)
    local function placeTiles( k )
        for i = k - 4, k + 4 do
            local s = ( ( i % L.SLOTS ) + L.SLOTS ) % L.SLOTS + 1
            local t = tiles[ s ]
            if t.idx ~= i then
                t.idx = i
                t:setLeftRight( true, false, i * L.TILE_PITCH, i * L.TILE_PITCH + L.TILE_W )
                paintTile( t, tileValue( i ), false )
            end
        end
    end

