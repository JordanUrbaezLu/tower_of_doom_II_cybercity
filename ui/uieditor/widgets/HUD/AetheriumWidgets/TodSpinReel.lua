-- THE DEALER'S GIFT: the companion (1..4) a reel value names, or nil for an item / CURSED / empty value.
function P3.GIFT.comp( v )
    v = tonumber( v ) or 0
    local c = v - P3.GIFT.base
    if c >= 1 and c <= P3.GIFT.n then
        return c
    end
    return nil
end

-- THE HOT STREAK (docs/201): the slices a heated roll uses before any guarantee - EPIC and LEGENDARY x the heat's
-- multiplier, COMMON pays. LOCKSTEP with _tod_shop.gsc roll_rarity. Returns { common, rare, epic, legendary }.
local function heatOdds( luck, heat )
    local c = 56 - 0.20 * luck
    local r = 27 + 0.09 * luck
    local e = 13 + 0.07 * luck
    local l = 100 - c - r - e
    local hm = P3.HEAT_MULT[ heat or 0 ] or 1
    c = c - ( e * hm - e ) - ( l * hm - l )
    return { c, r, e * hm, l * hm }
end

-- The TRUE odds a spin at this luck rolls with (_tod_shop.gsc roll_rarity): the line
-- from 56/27/13/4 (empty bar) to 36/36/20/8 (full), heated by THE HOT STREAK (heatOdds),
-- then the guarantees - 50+ luck lifts every COMMON to RARE; a full bar lifts every
-- COMMON / RARE to EPIC, 25 in 100 of those to LEGENDARY. Returns { common, rare, epic,
-- legendary } out of 100.
local function effOdds( luck, heat )
    local o = heatOdds( luck, heat )
    local c, r, e, l = o[ 1 ], o[ 2 ], o[ 3 ], o[ 4 ]
    if luck >= 100 then
        e = e + ( c + r ) * 0.75
        l = l + ( c + r ) * 0.25
        c, r = 0, 0
    elseif luck >= 50 then
        r = r + c
        c = 0
    end
    return { c, r, e, l }
end

local function unpackTile( v )
    v = tonumber( v ) or 0
    if v <= 0 then
        return nil
    end
    local item = math.floor( v / 4 )
    local rar = v - item * 4
    if not ITEMS[ item ] then
        return nil
    end
    return item, rar
end

-- Deterministic, plain arithmetic only (L3akMod-safe): the same seed + index
-- always yields the same tile, so a tile can be rebuilt at any time.
local function lcg( seed, i )
    local x = ( seed * 7 + ( i + 1000 ) * 131 ) % 65537
    for _ = 1, 3 do
        x = ( x * 75 + 74 ) % 65537
    end
    return x
end

-- docs/187 odds, a straight line from an empty bar to a full one, heated by THE HOT
-- STREAK (LOCKSTEP with _tod_shop.gsc roll_rarity): a hot player's reel visibly runs hotter.
local function fillerRarity( roll100, luck, heat )
    local o = heatOdds( luck, heat )
    local c, r, e = o[ 1 ], o[ 2 ], o[ 3 ]
    if roll100 < c then
        return 0
    elseif roll100 < c + r then
        return 1
    elseif roll100 < c + r + e then
        return 2
    end
    return 3
end

local function makeText( parent, opts )
    local t
    if CoD.TodGlyphText then
        t = CoD.TodGlyphText.new( opts )
    else
        t = LUI.UIText.new()
        t:setLeftRight( true, false, opts.left, opts.right )
        t:setTopBottom( true, false, opts.top, opts.bottom )
        if opts.align == "center" then
            t:setAlignment( Enum.LUIAlignment.LUI_ALIGNMENT_CENTER )
        elseif opts.align == "right" then
            t:setAlignment( Enum.LUIAlignment.LUI_ALIGNMENT_RIGHT )
        end
        if opts.rgb then
            t:setRGB( opts.rgb[ 1 ], opts.rgb[ 2 ], opts.rgb[ 3 ] )
        end
    end
    parent:addElement( t )
    return t
end

local function quad( parent, l, r, t, b, rgb, a )
    local q = LUI.UIImage.new()
