        -- THE DEALER'S GIFT: the filler is the four companions (the same LCG, so a tile can be rebuilt at any time)
        if st.gift then
            return P3.GIFT.base + ( lcg( st.seed + 29, i ) % P3.GIFT.n ) + 1
        end
        -- THE NEAR MISS: STOPPED SHORT's better tile waits just past the prize, SLIPPED PAST's jackpot just before it
        if st.tease > 0 and ( ( st.nearKind == 1 and i == st.land + 1 ) or ( st.nearKind == 2 and i == st.land - 1 ) ) then
            return st.tease
        end
        local rar = fillerRarity( lcg( st.seed, i ) % 100, st.luck, st.heat )
        local item = ( lcg( st.seed + 17, i ) % ITEM_COUNT ) + 1
        return item * 4 + rar
    end

    local function paintTile( t, v, hot )
        if v == CURSED.tile then
