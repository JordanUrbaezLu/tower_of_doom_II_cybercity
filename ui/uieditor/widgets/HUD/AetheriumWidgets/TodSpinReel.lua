    local function oddsPaint( luck, ms )
        local o = effOdds( luck, st.heat )
        local x = P3.ODDS_X0
        local w = P3.ODDS_X1 - P3.ODDS_X0
        for r = 0, 3 do
            local seg = fx.odds[ r ]
            local x1 = x + w * o[ r + 1 ] / 100
            seg:completeAnimation()
            if ms and ms > 0 then
                seg:beginAnimation( "tod_spin_odds", ms, false, false, CoD.TweenType.Linear )
            end
            seg:setLeftRight( true, false, x, x1 )
            seg:setAlpha( ( x1 - x > 0.5 ) and 1 or 0 )
            x = x1
        end
    end

    -- the caption under the odds. ONE SEGMENT SHORT (docs/201 section 6, the honest almost-hit): a bar that
    -- stopped one segment under a guarantee says so - true information, and the next spin's reason to bank luck.
    local function oddsCaption( luck )
        if luck >= 100 then
            return "FULL LUCK - EPIC OR BETTER"
        elseif luck >= 90 then
            return "ONE SEGMENT FROM AN EPIC"
        elseif luck >= 50 then
            return "RARE OR BETTER GUARANTEED"
        elseif luck >= 40 then
            return "ONE SEGMENT FROM A RARE"
        elseif ( st.heat or 0 ) > 0 then
            return "HOT STREAK - BETTER ODDS"
        end
        return "YOUR LUCK SETS THE ODDS"
    end

