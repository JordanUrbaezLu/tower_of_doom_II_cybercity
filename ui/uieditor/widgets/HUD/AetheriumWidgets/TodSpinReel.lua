    local function onOpen( d )
        st.seed = ( type( d[ 1 ] ) == "number" and d[ 1 ] ) or 1
        st.prize = ( type( d[ 2 ] ) == "number" and d[ 2 ] ) or 0
        -- the packed tease (docs/201): heat * 256 + near-miss kind * 64 + the teased tile (item * 4 + rarity); a
        -- bare tile with no kind is the old one-past tease, drawn as STOPPED SHORT
        local tz = ( type( d[ 3 ] ) == "number" and d[ 3 ] ) or 0
        if tz < 0 then tz = 0 end
        st.heat = math.floor( tz / 256 )
        if st.heat > 3 then st.heat = 3 end
        st.nearKind = math.floor( ( tz % 256 ) / 64 )
        st.tease = tz % 64
        if st.tease > 0 and st.nearKind == 0 then st.nearKind = 1 end
        if st.tease == 0 then st.nearKind = 0 end
        local ll = ( type( d[ 4 ] ) == "number" and d[ 4 ] ) or 30
        st.luck = math.floor( ll / 64 )
        st.land = ll - st.luck * 64
        -- THE DEALER'S GIFT (docs/209): a companion tile as the prize = a gift reel (no tease, no heat, no pour)
        st.gift = ( P3.GIFT.comp( st.prize ) ~= nil )
        if st.gift then
            st.heat, st.nearKind, st.tease = 0, 0, 0
        end
        for s = 1, L.SLOTS do
            tiles[ s ].idx = nil
        end
        Strip:completeAnimation()
        Strip:setLeftRight( true, false, stripX( 0 ), stripX( 0 ) + 1 )
        placeTiles( 0 )
        LuckText:setText( "LUCK " .. st.luck )
        st.code = 0
        resetResult()
        st.open = true
        veilSet( true )
        watchStart()
        -- THE SLAM: the panel drops in from above and settles (Bounce), the room dims with it
        Panel:completeAnimation()
        Panel:setTopBottom( true, true, P3.SLAM_Y, P3.SLAM_Y )
        Panel:setAlpha( 0 )
        Panel:beginAnimation( "tod_spin_in", P3.SLAM_MS, false, false, CoD.TweenType.Bounce )
        Panel:setTopBottom( true, true, 0, 0 )
        Panel:setAlpha( 1 )
        -- PASS 3: every piece a previous spin could leave mid-tween starts clean (the
        -- dim after a LEGENDARY flash, the needle's tilt)
        fx.dim:completeAnimation()
        fx.dim:setRGB( 0, 0, 0 )
        fx.dim:setAlpha( P3.DIM_A )
        if fx.needle then
            fx.needle:completeAnimation()
            fx.needle:setZRot( 0 )
        end
        -- PASS 3: what the spin rolls and who it is for
        st.flown, st.scrapped, st.pulse, st.landed = false, false, nil, false
        spinInfo( true )
        -- THE DEALER'S GIFT (docs/209): nothing is rolled against the luck, so no odds bar and no heat; the
        -- companion window waits EMPTY for the one the reel gives him (it punches in at the landing)
        local cname = ( not st.gift ) and P3.COMPANIONS[ st.comp ] or nil
        if st.gift then
            fx.forText:setText( P3.GIFT.forLine )
            fx.oddsCap:setText( P3.GIFT.caption )
            fx.oddsBack:setAlpha( 0 )
            for r = 0, 3 do
                fx.odds[ r ]:setAlpha( 0 )
            end
            heatChip( 0, false )
        else
            fx.forText:setText( cname and ( "FOR YOUR " .. cname ) or "" )
            fx.oddsCap:setText( "YOUR LUCK SETS THE ODDS" )
            oddsPaint( 0, 0 )
            -- THE HOT STREAK (docs/201): the heat this spin rolls with, by name, beside the odds it heats
            heatChip( st.heat, false )
        end
        -- PASS 3 ART: the dealer waits; the companion that gets the item is shown (its
        -- whole window stays hidden if the loadout never arrived)
        st.pose = nil
        pose( "idle", CYAN, 0 )
        streaksOff()
        if fx.comp then
            local a = cname and 1 or 0
            fx.comp.clip:setAlpha( a )
            fx.comp.frame:setAlpha( a )
            fx.comp.name:setAlpha( a )
            if cname then
                fx.comp.pic:setImage( reg( ART.comp[ st.comp ] ) )
                fx.comp.name:setText( cname )
                popIn( fx.comp, CYAN, 0 )
            end
        end
        -- THE POUR: the luck counter drains into the machine, motes fly from the LUCK box
        -- into the reel, and the odds slide from the empty-bar line to the bought odds.
        -- THE DEALER'S GIFT (docs/209): NOTHING POURS - his bar stays in the box, untouched (the user's rule)
        st.pouring = not st.gift
        if not st.pouring then
            for i = 1, #fx.motes do
                fx.motes[ i ]:completeAnimation()   -- a previous spin's motes rest faintly on the reel: none on a gift
                fx.motes[ i ]:setAlpha( 0 )
            end
        else
            oddsPaint( st.luck, P3.POUR_MS )
            luckCount( st.luck, 0, P3.POUR_MS )
            -- a hot player's luck pours in as embers
            local mc = ( st.heat > 0 ) and P3.HEAT_RGB or P3.MOTE_RGB
            for i = 1, #fx.motes do
                fx.motes[ i ]:setRGB( mc[ 1 ], mc[ 2 ], mc[ 3 ] )
            end
            if st.luck > 0 then
                for i = 1, #fx.motes do
                    moteFly( fx.motes[ i ], P3.LUCK_CX, P3.LUCK_CY, P3.TILE_CX + ( i - 3.5 ) * 20, P3.TILE_CY, ( i - 1 ) * ( P3.POUR_MS - P3.MOTE_MS ) / #fx.motes )
                end
            end
        end
        -- the rail runners wake up (they move one hop per reel step)
        for i, rn in ipairs( fx.runners ) do
            rn.x = P3.RAIL_X0 + ( i - 1 ) * ( P3.RAIL_X1 - P3.RAIL_X0 ) / #fx.runners
            local y = rn.top and P3.RAIL_Y or P3.WIN_Y
            rn.el:completeAnimation()
            -- the light pulses: the theme's lit red on the top rail, unlit steel below (synthwave: pink / cyan)
            local rc = rn.top and P3.THEME.railTop or P3.THEME.railLow
            rn.el:setRGB( rc[ 1 ], rc[ 2 ], rc[ 3 ] )
            rn.el:setLeftRight( true, false, rn.x, rn.x + P3.RUN_W )
            rn.el:setTopBottom( true, false, y, y + P3.RUN_H )
            rn.el:setAlpha( 0.9 )
        end
    end

    local function onStep( d )
        local k = ( type( d[ 1 ] ) == "number" and d[ 1 ] ) or 0
        local ms = ( type( d[ 2 ] ) == "number" and d[ 2 ] ) or 50
        pourFinish()   -- a step (or a resume jump) always lands the pour
        placeTiles( k )
        Strip:completeAnimation()
        -- THE NEAR MISS (docs/201): the last step of a near-miss spin is long (the server's own ms); a resume after a
        -- card deal re-sends it at 50 ms, which just puts the prize under the needle like any other jump
        local near = ( k == st.land and k > 0 and st.nearKind > 0 )
        if near and st.nearKind == 1 and ms > P3.NEAR_HANG_MS + P3.SETTLE_MS + 60 then
            -- STOPPED SHORT: run past the prize to the seam of the better tile (the run's handler hangs it there)
            Strip:beginAnimation( "tod_spin_nearrun", ms - P3.NEAR_HANG_MS - P3.SETTLE_MS, false, false, CoD.TweenType.Linear )
            Strip:setLeftRight( true, false, stripX( k ) - P3.NEAR_EDGE, stripX( k ) - P3.NEAR_EDGE + 1 )
        elseif near and st.nearKind == 2 and ms > P3.PAST_HOLD_MS + 60 then
            -- SLIPPED PAST: creep across the jackpot under the needle, glowing - never a stop (the creep's handler
            -- crawls on to the prize)
            st.slipMs = ms - P3.PAST_HOLD_MS
            Strip:beginAnimation( "tod_spin_creep", P3.PAST_HOLD_MS, false, false, CoD.TweenType.Linear )
            Strip:setLeftRight( true, false, stripX( k - 1 ) - P3.PAST_CREEP, stripX( k - 1 ) - P3.PAST_CREEP + 1 )
            nearGlowAt( P3.TILE_CX, st.tease, P3.PAST_GLOW_A, P3.PAST_HOLD_MS * 0.4 )
        elseif k == st.land and k > 0 and ms > P3.SETTLE_MS + 60 then
            -- THE STOP: run a little past the prize, then settle back onto it (Bounce)
            Strip:beginAnimation( "tod_spin_over", ms - P3.SETTLE_MS, false, false, CoD.TweenType.Linear )
            Strip:setLeftRight( true, false, stripX( k ) - P3.OVERSHOOT, stripX( k ) - P3.OVERSHOOT + 1 )
        else
            Strip:beginAnimation( "tod_spin_step", ms, false, false, CoD.TweenType.Linear )
            Strip:setLeftRight( true, false, stripX( k ), stripX( k ) + 1 )
