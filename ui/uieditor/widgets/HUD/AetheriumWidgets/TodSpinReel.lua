    q:setTopBottom( true, false, t, b )
    q:setRGB( rgb[ 1 ], rgb[ 2 ], rgb[ 3 ] )
    q:setAlpha( a )
    parent:addElement( q )
    return q
end

-- Images are registered ONCE (the luck-bar pattern in tod_upgrade.lua) and set
-- by handle; `pic` builds an image element in a rect.
local IMG = {}
local function reg( name )
    if not IMG[ name ] then
        IMG[ name ] = RegisterImage( name )
    end
    return IMG[ name ]
end

local function pic( parent, l, r, t, b, name, a )
    local e = LUI.UIImage.new()
    e:setLeftRight( true, false, l, r )
    e:setTopBottom( true, false, t, b )
    if name then
        e:setImage( reg( name ) )
    end
    e:setAlpha( a or 1 )
    parent:addElement( e )
    return e
end

