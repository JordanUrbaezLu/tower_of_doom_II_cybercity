                fx.ring:setLeftRight( true, false, P3.TILE_CX - r1, P3.TILE_CX + r1 )
                fx.ring:setTopBottom( true, false, P3.TILE_CY - r1, P3.TILE_CY + r1 )
                fx.ring:setAlpha( 0 )
            end
            if rar >= 2 then
                burst( P3.TILE_CX, P3.TILE_CY, col, 110 + 45 * ( rar - 2 ), P3.SHARDS )
                if fx.edge then
                    fx.edge:completeAnimation()
                    fx.edge:setRGB( col[ 1 ], col[ 2 ], col[ 3 ] )
                    fx.edge:setAlpha( ( rar >= 3 ) and 0.9 or 0.55 )
                    fx.edge:beginAnimation( "tod_spin_edge", 1200 + 600 * ( rar - 2 ), false, false, CoD.TweenType.Linear )
                    fx.edge:setAlpha( 0 )
                end
            end
            if rar >= 3 then
                fx.dim:completeAnimation()
                fx.dim:setRGB( 1, 0.86, 0.5 )
                fx.dim:setAlpha( 0.5 )
                fx.dim:beginAnimation( "tod_spin_flash", 380, false, false, CoD.TweenType.Linear )
                fx.dim:setRGB( 0, 0, 0 )
                fx.dim:setAlpha( P3.DIM_A )
                st.shake = 4
                Panel:completeAnimation()
                Panel:beginAnimation( "tod_spin_shake", 45, false, false, CoD.TweenType.Linear )
                Panel:setTopBottom( true, true, 7, 7 )
            end
        end
        PrizeName:setText( ITEMS[ item ].name )
        PrizeFx:setText( ITEMS[ item ].fx[ rar + 1 ] )
        -- code: 1 socketed in an empty slot, 2 upgraded in place, 3 choose a slot
        if code == 1 then
            Status:setText( "SOCKETED" )
        elseif code == 2 then
            Status:setText( "UPGRADED" )
        elseif code == 3 then
            Status:setText( "CHOOSE A SLOT" )
        else
            Status:setText( "" )
        end
    end

    Panel:registerEventHandler( "transition_complete_tod_spin_shake", function ( element, event )
        if event and event.interrupted then
            return
        end
        st.shake = st.shake - 1
        local off = ( st.shake == 3 and -5 ) or ( st.shake == 2 and 3 ) or ( st.shake == 1 and -1 ) or 0
        if st.shake <= 0 then
            Panel:setTopBottom( true, true, 0, 0 )
            return
        end
        Panel:beginAnimation( "tod_spin_shake", 45, false, false, CoD.TweenType.Linear )
        Panel:setTopBottom( true, true, off, off )
    end )

    -- the flying prize lands in its slot: the slot's icon appears and the slot flashes
    if fx.flyer then
        fx.flyer:registerEventHandler( "transition_complete_tod_spin_fly", function ( element, event )
            fx.flyer:setAlpha( 0 )
            local box = st.flyBox and boxes[ st.flyBox ]
            if not box then
                return
            end
            box.Icon:setAlpha( 1 )
            fx.boxFlash:completeAnimation()
            fx.boxFlash:setLeftRight( true, false, box.x0, box.x0 + L.BOX_W )
            fx.boxFlash:setAlpha( 0.85 )
            fx.boxFlash:beginAnimation( "tod_spin_boxflash", 280, false, false, CoD.TweenType.Linear )
            fx.boxFlash:setAlpha( 0 )
            -- PASS 3 ART: the power flows into the companion (its window flashes the prize's colour)
            if fx.comp and st.flyCol then
                popIn( fx.comp, st.flyCol, 0.7 )
            end
        end )
    end

    -- mode 0 = show the three slots; 1 = choosing (focus + hold bar, SCRAP shown);
    -- 2 = RESULT, installed in slot (focus + 1); 3 = RESULT, scrapped (the
    -- hundreds carry the luck paid back); 4 = THE DEALER'S GIFT (docs/209): the new
    -- companion's three slots, empty, each saying SPIN TO FILL - what the counter is for next time.
    -- THE DEALER'S GIFT (docs/209): THE POOL - box b shows companion b (its portrait, its name, COMPANION over it)
    local function paintPool()
        local G = P3.GIFT
        local col = G.col
        for b = 1, 4 do
            local box = boxes[ b ]
            setBoxVisible( box, true )
            box.Focus:setAlpha( 0 )
            box.Hold:setAlpha( 0 )
            box.Label:setText( G.foot )
            if USE_SPIN_ART then
                box.Sock:setImage( reg( ART.socket ) )
                box.Sock:setRGB( col[ 1 ], col[ 2 ], col[ 3 ] )
                box.Icon:setImage( reg( ART.gift.icon[ b ] ) )
                box.Icon:setRGB( 1, 1, 1 )
                box.Icon:setAlpha( 1 )
            else
                box.Stripe:setRGB( col[ 1 ], col[ 2 ], col[ 3 ] )
                box.Plate:setRGB( col[ 1 ] * 0.14, col[ 2 ] * 0.14, col[ 3 ] * 0.14 )
            end
            box.Name:setText( G.short[ b ] )
            box.Name:setRGB( 1, 1, 1 )
            box.Rar:setText( "" )
        end
        Hint:setAlpha( 0 )
    end

    local function onSlots( d )
        local packed = ( type( d[ 4 ] ) == "number" and d[ 4 ] ) or 0
        local hold = math.floor( packed / 100 )
        local focus = math.floor( ( packed - hold * 100 ) / 10 )
        local mode = packed - hold * 100 - focus * 10
        if mode == P3.GIFT.poolMode then
            paintPool()
            return
        end
        if USE_SPIN_ART then
            boxes[ 4 ].Sock:setImage( reg( ART.scrap ) )   -- after THE POOL, box 4 is the SCRAP box again
            boxes[ 4 ].Sock:setRGB( 1, 1, 1 )
            boxes[ 4 ].Icon:setAlpha( 0 )
        end
        local emptyText = ( mode == P3.GIFT.slotsMode ) and P3.GIFT.empty or "EMPTY"
        for b = 1, 3 do
            local box = boxes[ b ]
            setBoxVisible( box, true )
            paintBox( box, "SLOT " .. b, d[ b ], emptyText )
        end
        local sb = boxes[ 4 ]
        local scrapOn = ( mode == 1 or mode == 3 )
        setBoxVisible( sb, scrapOn )
        if scrapOn and not USE_SPIN_ART then
            -- the flat lane spells SCRAP out; the art bakes it
            sb.Label:setText( "OR" )
            sb.Stripe:setRGB( 0.35, 0.95, 1 )
            sb.Plate:setRGB( 0.02, 0.1, 0.12 )
            sb.Name:setText( "SCRAP" )
            sb.Name:setRGB( 1, 1, 1 )
            sb.Rar:setText( "BACK TO LUCK" )
            sb.Rar:setRGB( 0.35, 0.95, 1 )
        else
            sb.Label:setText( "" )
            sb.Name:setText( "" )
            sb.Rar:setText( "" )
        end
        if mode == 2 then
            Status:setText( ( ( st.code == 2 ) and "UPGRADED IN SLOT " or "SOCKETED IN SLOT " ) .. ( focus + 1 ) )
            -- PASS 3: the prize flies into its slot (once per spin; a repaint after a
            -- pause just shows it), and its chip pulses once the HUD comes back
            local item, rar = unpackTile( d[ focus + 1 ] )
            if item and focus >= 0 and focus <= 2 then
                st.pulse = focus + 1
                if fx.flyer and not st.flown then
                    st.flown = true
                    local box = boxes[ focus + 1 ]
                    local col = RARITY[ rar ].col
                    st.flyBox = focus + 1
                    st.flyCol = col
                    box.Icon:setAlpha( 0 )
                    fx.flyer:completeAnimation()
                    fx.flyer:setImage( reg( ART.icon[ item ] ) )
                    fx.flyer:setRGB( col[ 1 ], col[ 2 ], col[ 3 ] )
                    fx.flyer:setLeftRight( true, false, P3.TILE_CX - 26, P3.TILE_CX + 26 )
                    fx.flyer:setTopBottom( true, false, P3.TILE_CY - 44, P3.TILE_CY + 8 )
                    fx.flyer:setAlpha( 1 )
                    fx.flyer:beginAnimation( "tod_spin_fly", P3.FLY_MS, false, false, CoD.TweenType.Linear )
                    fx.flyer:setLeftRight( true, false, box.x0 + L.S_ICON[ 1 ], box.x0 + L.S_ICON[ 3 ] )
                    fx.flyer:setTopBottom( true, false, L.BOX_Y0 + L.S_ICON[ 2 ], L.BOX_Y0 + L.S_ICON[ 4 ] )
                end
            end
        elseif mode == 3 then
            Status:setText( "SCRAPPED FOR " .. hold .. " LUCK" )
            -- PASS 3: the prize breaks up at SCRAP and its luck flies back to the counter
            if not st.scrapped then
                st.scrapped = true
                local sx = boxes[ 4 ].x0 + L.BOX_W / 2
                local sy = L.BOX_Y0 + L.BOX_H / 2
                burst( sx, sy, P3.THEME.focus, 70, P3.SHARDS )
                for i = 1, #fx.motes do
                    fx.motes[ i ]:setRGB( P3.MOTE_RGB[ 1 ], P3.MOTE_RGB[ 2 ], P3.MOTE_RGB[ 3 ] )   -- luck flies back as luck, never as embers
                    moteFly( fx.motes[ i ], sx + ( i - 3.5 ) * 12, sy, P3.LUCK_CX, P3.LUCK_CY, 120 + ( i - 1 ) * 45 )
                end
                luckCount( 0, hold, P3.POUR_MS )
            end
        end
        for b = 1, 4 do
            local box = boxes[ b ]
            local on = ( mode >= 1 and mode <= 3 and focus == b - 1 )   -- the gift's row (mode 4) rings nothing
            box.Focus:setAlpha( on and 1 or 0 )
            if not USE_SPIN_ART then
                -- the flat lane rings the installed slot in its rarity colour
                local item, rar = unpackTile( d[ b ] )
                local col = ( mode == 2 and rar and RARITY[ rar ].col ) or P3.THEME.focus
                box.Focus:setRGB( col[ 1 ], col[ 2 ], col[ 3 ] )
            end
            if mode == 1 and on and hold > 0 then
                box.Hold:setLeftRight( true, false, box.x0, box.x0 + L.BOX_W * math.min( hold, 10 ) / 10 )
                box.Hold:setAlpha( 1 )
            else
                box.Hold:setAlpha( 0 )
            end
        end
        if mode == 1 then
            Hint:setText( Engine.Localize( "^3[{+smoke}]^7 ^5<  MOVE  >^7 ^3[{+frag}]^7      HOLD ^3[{+gostand}]^7 TO CONFIRM" ) )
            Hint:setAlpha( 1 )
        else
            Hint:setAlpha( 0 )
        end
    end

    local function onEnd()
        st.open = false
        st.pouring = false
        veilSet( false )
        watchStop()
        Panel:completeAnimation()
        Panel:beginAnimation( "tod_spin_out", 250, false, false, CoD.TweenType.Linear )
        Panel:setTopBottom( true, true, P3.OUT_Y, P3.OUT_Y )
        Panel:setAlpha( 0 )
    end

    -- PASS 3: the chip of the item just socketed pulses twice when the HUD returns
    local function chipPulse( c )
        local chip = chips[ c ]
        if not ( chip and chip.Flash ) then
            return
        end
        st.pulseN = 4
        chip.Flash:completeAnimation()
        chip.Flash:setAlpha( 0 )
        chip.Flash:beginAnimation( "tod_spin_chip", 140, false, false, CoD.TweenType.Linear )
        chip.Flash:setAlpha( 0.9 )
    end
    for c = 1, 3 do
        local chip = chips[ c ]
        if chip.Flash then
            chip.Flash:registerEventHandler( "transition_complete_tod_spin_chip", function ( element, event )
                if event and event.interrupted then
                    return
                end
                st.pulseN = st.pulseN - 1
                if st.pulseN <= 0 then
                    element:setAlpha( 0 )
                    return
                end
                element:beginAnimation( "tod_spin_chip", 140, false, false, CoD.TweenType.Linear )
                element:setAlpha( ( st.pulseN % 2 == 1 ) and 0 or 0.9 )
            end )
        end
    end

    Watch:registerEventHandler( "transition_complete_tod_spin_watch", function ( element, event )
        if event and event.interrupted then
            return
        end
        if st.open then
            onEnd()
        end
    end )

    -- The panel is closed with its menu (death -> spectate, a HUD rebuild): never
    -- leave the veil held by a reel that no longer exists.
    LUI.OverrideFunction_CallOriginalSecond( self, "close", function ( element )
        if st.open then
            st.open = false
            veilSet( false )
        end
    end )

    if CoD.TodHudVeil and CoD.TodHudVeil.Listen then
        CoD.TodHudVeil.Listen( self, function ( hidden )
            st.veiled = hidden
            applyChips()
            if not hidden and not st.open and st.pulse then
                local c = st.pulse
                st.pulse = nil
                chipPulse( c )
            end
        end )
    end

    local function onItems( d )
        local comp = ( type( d[ 4 ] ) == "number" and d[ 4 ] ) or 0
        st.comp = comp
        -- the pause menu / scoreboard companion row reads this (CoD.TodCompanionDescribe)
        local rec = CoD.TodCompanion
        rec.comp = comp
        if comp > 0 then
            rec.items[ comp ] = { tonumber( d[ 1 ] ) or 0, tonumber( d[ 2 ] ) or 0, tonumber( d[ 3 ] ) or 0 }
        end
        if comp <= 0 then
            st.chipsWant = false
            applyChips()
            return
        end
        local any = false
        for c = 1, 3 do
            local chip = chips[ c ]
            local item, rar = unpackTile( d[ c ] )
            if item then
                any = true
                local col = RARITY[ rar ].col
                if USE_SPIN_ART then
                    chip.Img:setRGB( col[ 1 ], col[ 2 ], col[ 3 ] )
                    chip.Icon:setImage( reg( ART.icon[ item ] ) )
                    chip.Icon:setRGB( col[ 1 ], col[ 2 ], col[ 3 ] )
                    chip.Icon:setAlpha( 1 )
                else
                    chip.Plate:setRGB( col[ 1 ] * 0.3, col[ 2 ] * 0.3, col[ 3 ] * 0.3 )
                    chip.Edge:setRGB( col[ 1 ], col[ 2 ], col[ 3 ] )
                    chip.Name:setText( ITEMS[ item ].chip )
                    chip.Name:setRGB( col[ 1 ], col[ 2 ], col[ 3 ] )
                end
                chip:setAlpha( 1 )
            else
                if USE_SPIN_ART then
                    chip.Img:setRGB( EMPTY_RIM[ 1 ], EMPTY_RIM[ 2 ], EMPTY_RIM[ 3 ] )
                    chip.Icon:setAlpha( 0 )
                else
                    chip.Plate:setRGB( 0.1, 0.1, 0.12 )
                    chip.Edge:setRGB( 0.3, 0.3, 0.32 )
                    chip.Name:setText( "" )
                end
                chip:setAlpha( 0.35 )
            end
        end
        st.chipsWant = any
        applyChips()
    end

    -- read by tools/test_spin_reel.lua only (the pass-3 elements + state)
    fx.boxes, fx.luckText, fx.st = boxes, LuckText, st
    self.p3 = fx

    self:subscribeToGlobalModel( InstanceRef, "PerController", "scriptNotify", function ( model )
        local name = Engine.GetModelValue( model )
        if name ~= "tod_spin_open" and name ~= "tod_spin_step" and name ~= "tod_spin_land"
           and name ~= "tod_spin_slots" and name ~= "tod_spin_end" and name ~= "tod_ptn_items"
           and name ~= "tod_ptn_state" and name ~= "tod_luck_heat" and name ~= "tod_ptn_hud" then
            return
        end
        local d = CoD.GetScriptNotifyData( model ) or {}
        if name == "tod_ptn_hud" then
            -- ( companion + 1, state, value, len, flags ): the status plate's own event (TodCompanionPlate.lua);
            -- the chips only follow whether the plate shows (flags 2 = its owner is dead / spectating)
            local comp, flags = tonumber( d[ 1 ] ) or 0, tonumber( d[ 5 ] ) or 0
            st.ptnOut = ( comp <= 0 ) or ( math.floor( flags / 2 ) % 2 == 1 )
            applyChips()
            return
        end
        if name == "tod_luck_heat" then
            -- THE HOT STREAK (docs/201): ( heat, streak, change ) - the spin's own result just moved it (the odds
            -- bar keeps the heat this spin ROLLED with; the chip shows where it stands now, pulsing on a rise)
            if st.open then
                heatChip( tonumber( d[ 1 ] ) or 0, ( tonumber( d[ 3 ] ) or 0 ) == 1 )
            end
            return
        end
        if name == "tod_spin_open" then
            onOpen( d )
        elseif name == "tod_spin_step" then
            onStep( d )
        elseif name == "tod_spin_land" then
            onLand( d )
        elseif name == "tod_spin_slots" then
            onSlots( d )
        elseif name == "tod_spin_end" then
            onEnd()
        elseif name == "tod_ptn_state" then
            -- ( companion + 1, state, value, built mask ): the companion row's state (see above)
            local rec = CoD.TodCompanion
            rec.comp, rec.state = tonumber( d[ 1 ] ) or 0, tonumber( d[ 2 ] ) or 0
            rec.value, rec.built = tonumber( d[ 3 ] ) or 0, tonumber( d[ 4 ] ) or 0
        else
            onItems( d )
        end
    end )

    return self
end
