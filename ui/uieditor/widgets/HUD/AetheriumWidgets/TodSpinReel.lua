function CoD.TodCompanionDescribe()
    local rec = CoD.TodCompanion or {}
    local comp = tonumber( rec.comp ) or 0
    -- status = the pause menu's grey line, short = the scoreboard's suffix after the name
    local out = { held = false, name = "AI COMPANION", slots = {}, items = "", status = "", short = "", tone = "idle" }
    if comp < 1 or not P3.COMPANIONS[ comp ] then
        -- THE DEALER'S GIFT (docs/209): a companion comes from ONE place - the Black Market's dealer gives each player
        -- one, free (the docs/159 parts and partner benches are retired, so "built" no longer changes what this says)
        out.items = "NONE YET"
        out.status = "the Black Market dealer gives you one free"
        return out
    end
    out.held, out.name, out.portrait = true, P3.COMPANIONS[ comp ], ART.comp[ comp ]
    local tiles = ( rec.items or {} )[ comp ] or {}
    local names, chips = {}, {}
    for c = 1, 3 do
        local item, rar = unpackTile( tiles[ c ] )
        if item then
            out.slots[ c ] = { icon = ART.icon[ item ], rgb = RARITY[ rar ].col, name = ITEMS[ item ].name }
            names[ #names + 1 ] = ITEMS[ item ].name
            chips[ #chips + 1 ] = ITEMS[ item ].chip
        else
            out.slots[ c ] = false
        end
    end
    -- ONE LINE, and it must fit the pause row (261 units): past 35 characters the longest full
    -- names give way to their chip labels one at a time ("HOLLOW POINT" -> "HOLLOW"). Measured
    -- in the map TTF over every combination: the worst line left is 241 units. The three
    -- longest names in full were 266.5 (tools/ui_mockup/render_menus.py caught it).
    while #table.concat( names, ", " ) > 35 do
        local j, len = nil, 0
        for k = 1, #names do
            if names[ k ] ~= chips[ k ] and #names[ k ] > len then
                j, len = k, #names[ k ]
            end
        end
        if not j then
            break
        end
        names[ j ] = chips[ j ]
    end
    out.items = ( #names > 0 ) and table.concat( names, ", " ) or "NO ITEMS - SPIN AT THE BLACK MARKET"
    local state, v = tonumber( rec.state ) or 0, tonumber( rec.value ) or 0
    if state == 1 then
        out.status, out.short, out.tone = "ACTIVE - HEALTH " .. v .. "%", "HEALTH " .. v .. "%", "good"
    elseif state == 2 then   -- the font draws S like 5: " sec"
        out.status, out.short, out.tone = "DESTROYED - BACK IN " .. v .. " sec", "BACK IN " .. v .. " sec", "hot"
    elseif state == 3 then
        out.status, out.short = "ON ITS WAY", "ON ITS WAY"
    end
    return out
end

