-- =============================================================================
-- TodGlyphRow — THE CUSTOM TYPEFACE, as a shared row factory.
--
-- LIFTED VERBATIM OUT OF AetheriumLoadout.lua (v17.25). Nothing in the layout
-- maths below changed; the file exists because a SECOND widget now sets text in
-- the baked typeface — the top-right ROUND readout, which replaced the stock
-- ZmRndContainer (user 2026-09-04: "We have the round image in the top right of
-- screen but I am looking to replace with the alphabet and letters we have
-- downloaded ... Lets remove stock and track ourselves").
--
-- ONE COPY, DELIBERATELY. The alternative was to paste the ~120 lines into the
-- round counter, and this map has a standing rule about exactly that: a second
-- copy of a number is a second source of truth that nothing regenerates. It is
-- worse here than usual, because the layout maths is the CONSUMER of the
-- GENERATED metrics in TodGlyphMetrics.lua — a re-slice would silently fix one
-- copy and not the other, and the failure mode is text that overlaps by two
-- pixels, which nobody files a bug about.
--
-- WHAT A CALLER GETS:
--   CoD.TodGlyphRow.make( owner, n )   a pooled row of n UIImages, with
--                                      .set / .measure / .hide / .setRGB
--   CoD.TodGlyphRow.digitSet           set picker: digits only (numbers)
--   CoD.TodGlyphRow.nameSet            set picker: letters, digits where they
--                                      appear (names — "AK-47", "ROUND 12")
-- The two image mappers are exported too, but only the pickers are normally
-- needed: .set resolves the image itself.
--
-- THE POOL IS THE POINT. Elements are created ONCE at construction and only
-- their image and rect are written per update. Creating and closing elements on
-- every tick is a documented state-pool leak in this tree.
-- =============================================================================

require( "ui.uieditor.widgets.HUD.AetheriumWidgets.TodGlyphMetrics" )  -- GENERATED by tools/slice_hud_sheets.js

-- =============================================================================
-- THE CUSTOM TYPEFACE
--
-- User 2026-09-03: "I wonder if we should get creative with digits and letters
-- as well so we can have custom text and numbers as well. That would be sick."
-- So every number and the weapon name in the gun HUD, and the ROUND readout in
-- the top-right corner, are assembled from baked glyph art. There is no system
-- font left in either corner.
--
-- HOW IT WORKS. Each glyph is one UIImage from a POOL created once at
-- construction — never per update. Creating and closing elements on every ammo
-- tick is what two weapon-swap UITimers in AetheriumLoadout used to do, and they
-- were a documented state-pool leak. Setting an image and a rect on a pooled
-- element allocates nothing.
--
-- METRICS ARE DERIVED, NOT TYPED. CoD.TodGlyphMetrics is GENERATED by
-- tools/slice_hud_sheets.js, which measures every cell's ink from its own alpha
-- channel. It carries, per set: the cell size, the baseline's y WITHIN the cell,
-- the cap height, and each glyph's ink width and left edge. Redraw a glyph
-- narrower and the spacing follows on the next slice — the art and its metrics
-- cannot drift.
--
-- WHY THE SETS ARE SEPARATE. A weapon name mixes both sheets ("AK-47",
-- "MP117 REDACTOR"), and they were drawn on different cells — digits 128x160
-- with a 137 cap, letters 80x112 with an 89 cap. Sitting them on one line means
-- scaling each set so its CAP HEIGHT matches, then aligning each set's own
-- BASELINE. Both numbers come out of the table, so neither is hardcoded here.
-- The two sets also both carry a "-", and they are different glyphs: the digit
-- one is the wide marker a blade shows in place of an ammo count, the letter one
-- is the hyphen inside "AK-47".
-- =============================================================================

-- A space has no glyph, only an advance. Expressed as a fraction of the cell so
-- it scales with everything else.
local TOD_SPACE_ADV  = 0.30
local TOD_TRACK      = 0.055   -- letter spacing, as a fraction of cap height

local function todDigitImage( c )
	if c >= "0" and c <= "9" then return "i_tod_hud_d" .. c end
	if c == "/" then return "i_tod_hud_dslash" end
	if c == "+" then return "i_tod_hud_dplus" end
	if c == "-" then return "i_tod_hud_ddash" end
	return nil
end

local TOD_LETTER_IMG = {
	[ "-" ] = "i_tod_hud_lhyphen",
	[ "'" ] = "i_tod_hud_lapos",
	[ "." ] = "i_tod_hud_ldot",
	-- v19.2: the map's own points icon, in the cell the dead ampersand used to
	-- hold. "$" therefore draws the SAME money symbol the player HUD shows, in
	-- every readout that uses this typeface -- no second currency mark exists.
	[ "$" ] = "i_tod_hud_lmoney",
}
local function todLetterImage( c )
	if c >= "A" and c <= "Z" then return "i_tod_hud_l" .. string.lower( c ) end
	return TOD_LETTER_IMG[ c ]
end

-- Which set a character belongs to, for a NAME (which may mix them).
local function todNameSet( c )
	if c >= "0" and c <= "9" then return "digits" end
	return "letters"
end

-- A POOLED ROW OF GLYPHS. `owner` is the element to add into; `n` the pool size.
-- set( str, cap, rightX, baselineY, setPicker ) lays the string out RIGHT-ALIGNED
-- and returns the width it used, or -1 if a character had no glyph.
local function todMakeGlyphRow( owner, n )
	local row = { img = {}, n = n }
	for i = 1, n do
		local e = LUI.UIImage.new()
		e:setLeftRight( true, false, 0, 1 )
		e:setTopBottom( true, false, 0, 1 )
		e:setImage( RegisterImage( "blacktransparent" ) )
		e:setRGB( 1, 1, 1 )
		e:setAlpha( 0 )
		owner:addElement( e )
		row.img[ i ] = e
	end

	row.hide = function ()
		for i = 1, n do row.img[ i ]:setAlpha( 0 ) end
	end

	-- Close every pooled element. LUI does NOT cascade close() to children --
	-- every widget in this tree closes its own by hand -- and a row owned by a
	-- SHORT-LIVED element leaks one element per pool slot without this. The
	-- +points popup is exactly that case: one is created per score event and
	-- closed when its animation ends.
	row.close = function ()
		for i = 1, n do row.img[ i ]:close() end
	end

	row.setRGB = function ( r, g, b )
		for i = 1, n do row.img[ i ]:setRGB( r, g, b ) end
	end

	-- Measure only. Returns width in canvas px, or -1 if any glyph is missing.
	row.measure = function ( str, cap, setPicker )
		local M = CoD.TodGlyphMetrics
		if not M then return -1 end
		local w, first = 0, true
		for i = 1, #str do
			local c = string.sub( str, i, i )
			if c == " " then
				local S = M.letters
				w = w + S.cw * ( cap / S.cap ) * TOD_SPACE_ADV
			else
				local setName = setPicker( c )
				local S = M[ setName ]
				local gm = S and S.g[ ( setName == "letters" ) and string.lower( c ) or c ]
				if not gm then return -1 end
				if not first then w = w + cap * TOD_TRACK end
				w = w + gm.adv * ( cap / S.cap )
			end
			first = false
		end
		return w
	end

	-- Draw. Same walk as measure, so the two can never disagree.
	row.set = function ( str, cap, rightX, baselineY, setPicker )
		local M = CoD.TodGlyphMetrics
		row.hide()
		if not M or str == nil or str == "" then return 0 end
		local total = row.measure( str, cap, setPicker )
		if total < 0 then return -1 end
		local pen, used, first = rightX - total, 0, true
		for i = 1, #str do
			if used >= n then break end
			local c = string.sub( str, i, i )
			if c == " " then
				local S = M.letters
				pen = pen + S.cw * ( cap / S.cap ) * TOD_SPACE_ADV
			else
				local setName = setPicker( c )
				local S = M[ setName ]
				local key = ( setName == "letters" ) and string.lower( c ) or c
				local gm = S and S.g[ key ]
				if gm then
					if not first then pen = pen + cap * TOD_TRACK end
					local s  = cap / S.cap             -- canvas px per source px
					local cw = S.cw * s                -- the whole cell, drawn
					local chh = S.ch * s
					-- place the CELL so the glyph's ink starts at pen and the
					-- set's own baseline lands on baselineY
					local left = pen - gm.x * s
					local top  = baselineY - S.baseline * s
					used = used + 1
					local e = row.img[ used ]
					e:setImage( RegisterImage( ( setName == "digits" ) and todDigitImage( c ) or todLetterImage( c ) ) )
					e:setLeftRight( true, false, left, left + cw )
					e:setTopBottom( true, false, top, top + chh )
					e:setAlpha( 1 )
					pen = pen + gm.adv * s
				end
			end
			first = false
		end
		return total
	end

	return row
end

-- Numbers use the digit set only; names may mix.
local function todSetDigits() return "digits" end

-- The export. Locals above stay local so nothing can reach past this table.
CoD.TodGlyphRow = {
	make        = todMakeGlyphRow,
	digitSet    = todSetDigits,
	nameSet     = todNameSet,
	digitImage  = todDigitImage,
	letterImage = todLetterImage,
}
