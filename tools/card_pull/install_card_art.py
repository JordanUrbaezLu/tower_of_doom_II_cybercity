def _alpha_img(w, h, fn):
    im = Image.new('RGBA', (w, h), (255, 255, 255, 0))
    px = im.load()
    for y in range(h):
        for x in range(w):
            a = fn(x + 0.5, y + 0.5)
            a = 0 if a < 0 else (1 if a > 1 else a)
            px[x, y] = (255, 255, 255, int(round(a * 255)))
    return im


def fx_glow():
    # the card aura: a soft rounded-rect halo, drawn 40 px proud of the card
    w, h = 320, 436
    mask = Image.new('L', (w, h), 0)
    ImageDraw.Draw(mask).rounded_rectangle([40, 40, w - 41, h - 41], radius=22, fill=255)
    mask = mask.filter(ImageFilter.GaussianBlur(16))
    im = Image.new('RGBA', (w, h), (255, 255, 255, 0))
    im.putalpha(mask)
    return im


def fx_rays():
    # 16 god rays alternating long / short: 8-fold symmetric, so a rotation of 45
    # degrees lands on the same picture (TodPull's rotation loop relies on this:
    # RAYS_PERIOD = 45 - LOCKSTEP)
    s = 512
    c = s / 2

    def f(x, y):
        dx, dy = x - c, y - c
        r = math.hypot(dx, dy)
        if r > c:
            return 0
        a = math.atan2(dy, dx)
        # 8 long + 8 short shafts
        wide = (0.5 + 0.5 * math.cos(16 * a)) ** 2.2
        long_ = 0.5 + 0.5 * math.cos(8 * a)          # alternating long / short
        reach = 110 + 120 * long_
        fall = math.exp(-(r / reach) ** 2) * min(1.0, r / 30.0)
        return wide * fall * 1.25 + 0.3 * math.exp(-(r / 46.0) ** 2)
    return _alpha_img(s, s, f)


def fx_shard():
    s = 64
    im = Image.new('RGBA', (s, s), (255, 255, 255, 0))
    glow = Image.new('L', (s, s), 0)
    ImageDraw.Draw(glow).polygon([(32, 6), (52, 32), (32, 58), (12, 32)], fill=150)
    glow = glow.filter(ImageFilter.GaussianBlur(4))
    core = Image.new('L', (s, s), 0)
    ImageDraw.Draw(core).polygon([(32, 10), (47, 32), (32, 54), (17, 32)], fill=255)
    out = Image.new('L', (s, s), 0)
    gp, cp, op = glow.load(), core.load(), out.load()
    for y in range(s):
        for x in range(s):
            op[x, y] = max(gp[x, y], cp[x, y])
    im.putalpha(out)
    return im


def fx_ring():
    s = 256
    c = s / 2

    def f(x, y):
        r = math.hypot(x - c, y - c)
        return math.exp(-((r - 100) / 7.0) ** 2) + 0.35 * math.exp(-((r - 100) / 18.0) ** 2)
    return _alpha_img(s, s, f)


def fx_flash():
    s = 256
    c = s / 2
    return _alpha_img(s, s, lambda x, y: math.exp(-(math.hypot(x - c, y - c) / 60.0) ** 2) * 1.1)


def fx_edge():
    # the screen-edge glow: transparent centre, soft light along all four edges
    w, h = 640, 360

    def f(x, y):
        d = min(x, y, w - x, h - y)
        return (max(0.0, 1 - d / 44.0)) ** 2.4   # thinner than v1 (70): read as a thick border
    return _alpha_img(w, h, f)


def fx_sweep():
    w, h = 64, 256

    def f(x, y):
        v = min(1.0, y / 24.0, (h - y) / 24.0)
        return math.exp(-((x - 32) / 11.0) ** 2) * v
    return _alpha_img(w, h, f)


PILL_CUT_V, PILL_CUT_H = 19.0, 15.7   # LOCKSTEP r10_card_chrome.py PILL_CUT_V / _H: 22 px at 45 degrees on the label


def fx_pill():
    # the title label + rarity band fill (tinted): a chamfered plate (top-left / bottom-right cut, the synthwave
    # grammar's only corner - it was a rounded pill until R10) with a lighter top half
    w, h = 432, 68
    ss = 4
    big = Image.new('L', (w * ss, h * ss), 0)
    cut = [(1, 1 + PILL_CUT_V), (1 + PILL_CUT_H, 1), (w - 1, 1), (w - 1, h - 1 - PILL_CUT_V), (w - 1 - PILL_CUT_H, h - 1),
           (1, h - 1)]
    ImageDraw.Draw(big).polygon([(x * ss, y * ss) for x, y in cut], fill=255)
    mask = big.resize((w, h), Image.LANCZOS)
    im = Image.new('RGBA', (w, h), (255, 255, 255, 0))
    px = im.load()
    mp = mask.load()
    for y in range(h):
        shade = 255 if y < h * 0.45 else int(255 - (y - h * 0.45) / (h * 0.55) * 40)
        for x in range(w):
            px[x, y] = (shade, shade, shade, mp[x, y])
    return im


