def _strip_gsc(t):
    t = re.sub(r'/\*.*?\*/', ' ', t, flags=re.S)
    out = []
    for line in t.split('\n'):
        q, i, cut = False, 0, len(line)
        while i < len(line):
            c = line[i]
            if q and c == '\\':
                i += 2
                continue
            if c == '"':
                q = not q
            elif not q and line.startswith('//', i):
                cut = i
                break
            i += 1
        out.append(line[:cut])
    return '\n'.join(out)


_STR = r'"(?:[^"\\\n]|\\.)*"'
_ADD = re.compile(r'\badd_domain\s*\(\s*"([a-z0-9_]+)"\s*,\s*' + _STR + r'\s*,\s*' + _STR +
                  r'\s*,\s*[^,()]+,\s*(undefined|array\s*\(([^)]*)\))')


def class_domains(problems):
    """{class key: {domain id: domain key}} for every card each class can be dealt: the
    add_domain calls that are not commented out (class keys `undefined` = every class),
    ids from domain_id(), class keys from tod_upgrade.lua TOD_TCLS. The TIER card is
    separate (PROMO_TIERS)."""
    up = _strip_gsc(io.open(UPGRADES_GSC, encoding='utf-8', errors='replace').read())
    ui = _strip_gsc(io.open(UPGRADE_UI_GSC, encoding='utf-8', errors='replace').read())
    lua = io.open(UPGRADE_LUA, encoding='utf-8', errors='replace').read()
    m = re.search(r'local\s+TOD_TCLS\s*=\s*\{([^}]*)\}', lua)
    classes = re.findall(r'"([a-z_]+)"', m.group(1)) if m else []
    blk = re.search(r'function\s+domain_id\b[\s\S]*?\n\}', ui)
    key_id = dict((k, int(v)) for k, v in
                  re.findall(r'case\s+"([a-z0-9_]+)"\s*:\s*return\s+(\d+)', blk.group(0) if blk else ''))
    calls = len(re.findall(r'\badd_domain\s*\(\s*"', up))
    found = _ADD.findall(up)
    if not classes or not key_id or not calls or len(found) != calls:
        problems.append('could not read the card list (TOD_TCLS %d classes, domain_id %d cases, add_domain %d calls, '
                        '%d parsed) - update class_domains() in this installer' % (len(classes), len(key_id), calls, len(found)))
        return {}
    out = dict((c, {}) for c in classes)
    for key, whole, keys in found:
        did = key_id.get(key)
        if did is None:
            problems.append('add_domain "%s" has no case in domain_id()' % key)
            continue
        for c in (classes if whole == 'undefined' else re.findall(r'"([a-z_]+)"', keys)):
            if c in out:
                out[c][did] = key
    return out


def v2_classes(installed, problems):
    """-> (the class keys drawn as layered cards, {other class: (card keys without art, tiers without art)})"""
    inst = set(installed)
    doms = class_domains(problems)
    if not all(n in inst for n in V2_CORE):
        return [], {}
    have = set(did for slug, did in ART_SLUGS.items() if 'i_tod_card2_art_' + slug in inst)
    done, gaps = [], {}
    for cls, ids in sorted(doms.items()):
        miss = sorted(ids[d] for d in ids if d not in have)
        tmiss = [t for t in PROMO_TIERS if ('i_tod_card2_art_tier_%s_%d' % (cls, t)) not in inst]
        if ids and not miss and not tmiss:
            done.append(cls)
        else:
            gaps[cls] = (miss, tmiss)
    return done, gaps


# The docs/191 layout (768 x 1152 canvas) - LOCKSTEP with docs/191_ref/card2_layout_template.png
# and TodPull.lua V2. Measured on every art-pack drop so a layer that drifted off the template
# is caught BEFORE a build (a generator nudging the window by 20 px looks fine alone and wrong
# stacked).
WINDOW = (96, 176, 672, 624)
KEEP_CLEAR = {'window': (110, 190, 658, 610), 'band': (180, 664, 588, 716),
              'text': (100, 764, 668, 960), 'pips': (196, 1006, 572, 1058)}


def _alpha_share(im, box, pred):
    px = im.getchannel('A').crop(box).tobytes()
    n = sum(1 for v in px if pred(v))
    return n / float(len(px))


def layout_warnings(name, im):
    w = []
    if name == 'i_tod_card2_body':
        # the window must be see-through EXCEPT where the crest socket (144 wide at
        # 640,576) overlaps its bottom-right corner - that overlap is the design
        a = im.getchannel('A')
        x0, y0, x1, y1 = KEEP_CLEAR['window']
        tot = see_n = 0
        for y in range(y0, y1, 2):
            for x in range(x0, x1, 2):
                if (x - 640) ** 2 + (y - 576) ** 2 <= 84 ** 2:
                    continue
                tot += 1
                if a.getpixel((x, y)) < 16:
                    see_n += 1
        see = see_n / float(tot)
        if see < 0.97:
            w.append('%s: the art WINDOW is only %d%% see-through (must be ~100%%: the illustration shows through it)' % (name, see * 100))
        for k in ('band', 'text', 'pips'):
            solid = _alpha_share(im, KEEP_CLEAR[k], lambda v: v > 200)
            if solid < 0.9:
                w.append('%s: the %s slot is not solid (%d%%) - the body must paint the dark slot there' % (name, k, solid * 100))
    elif name.startswith('i_tod_card2_frame_'):
        for k, box in KEEP_CLEAR.items():
            cover = _alpha_share(im, box, lambda v: v > 40)
            if cover > 0.04:
                w.append('%s: covers %d%% of the %s area (must stay clear - the game draws there)' % (name, cover * 100, k))
        plate = _alpha_share(im, (90, 50, 678, 134), lambda v: v > 200)
        if plate < 0.8:
            w.append('%s: the TITLE PLATE is only %d%% opaque (the game writes the title on it)' % (name, plate * 100))
    elif name.startswith('i_tod_card2_art_'):
        full = _alpha_share(im, (0, 0, im.size[0], im.size[1]), lambda v: v > 230)
        if full < 0.95:
            w.append('%s: only %d%% opaque - an illustration fills its whole window' % (name, full * 100))
    elif name == 'i_tod_card2_back':
        edge = _alpha_share(im, (0, 0, 8, 8), lambda v: v > 40)
        if edge > 0.2:
            w.append('%s: the corner is not transparent (rounded corners, like the body)' % name)
        # the game glows the back in the rarity colours: the art itself stays neutral
        small = im.resize((96, 144))
        rgb, al = small.convert('RGB').tobytes(), small.getchannel('A').tobytes()
        sat = 0
        for i in range(len(al)):
            r, g, b = rgb[3 * i], rgb[3 * i + 1], rgb[3 * i + 2]
            hi = max(r, g, b)
            if al[i] > 128 and hi > 50 and (hi - min(r, g, b)) > 0.25 * hi:
                sat += 1
        if sat > 0.01 * len(al):
            w.append('%s: %d%% of the back is coloured - it must be neutral (black / steel / white: the game adds '
                     'the rarity glow)' % (name, 100 * sat // len(al)))
        if name == 'i_tod_card2_back':
            # the v2 back must have the BODY's silhouette (the whole canvas), or the card
            # changes size when it flips
            box = im.getchannel('A').point(lambda v: 255 if v >= 128 else 0).getbbox()
            if box != (0, 0, im.size[0], im.size[1]):
                w.append('%s: its silhouette %s does not fill the canvas like the body - the card would change size '
                         'on the flip' % (name, box))
    return w


def pack_present(problems, warnings=None):
    have = []
    for name, (w, h) in sorted(PACK_SIZES.items()):
        p = png_path(name)
        if not os.path.exists(p):
            continue
        im = Image.open(p)
        if im.size != (w, h):
            problems.append('%s.png is %dx%d, must be %dx%d' % (name, im.size[0], im.size[1], w, h))
            continue
        if warnings is not None:
            warnings += layout_warnings(name, im.convert('RGBA'))
        have.append(name)
    return have


def lua_manifest(installed, classes=()):
    inst = set(installed)
    L = ['-- GENERATED by tools/card_pull/install_card_art.py (docs/187, docs/191) - DO NOT EDIT.',
         '-- The card-v2 / THE PULL images that are INSTALLED (a GDT block + a zone line each).',
         '-- tod_upgrade.lua and TodPull.lua only ever RegisterImage() names listed here.',
         'CoD.TodCardArt = {']
    L.append('    fx = {')
    for n in sorted(FX):
        if n in inst:
            L.append('        %s = "%s",' % (n.replace('i_tod_pull_', ''), n))
    L.append('    },')
    # no `back` key: the old back is retired whole (R10); TodPull.lua's BuildBack / BackPick take back2 when it is nil
    for key, n in (('body', 'i_tod_card2_body'), ('back2', 'i_tod_card2_back'), ('banner', 'i_tod_pull_banner')):
        if n in inst:
            L.append('    %s = "%s",' % (key, n))
    for key in ('frame', 'crest'):
        names = ['i_tod_card2_%s_%s' % (key, r) for r in RARITIES]
        if all(n in inst for n in names):
            L.append('    %s = { %s },' % (key, ', '.join('"%s"' % n for n in names)))
    L.append('    art = {')
    for slug, did in sorted(ART_SLUGS.items(), key=lambda kv: kv[1]):
        n = 'i_tod_card2_art_' + slug
        if n in inst:
            L.append('        [%d] = "%s",' % (did, n))
    L.append('    },')
    L.append('    tier = {')
    for cls, tiers in sorted(TIER_ART.items()):
        parts = ['[%d] = "i_tod_card2_art_tier_%s_%d"' % (t, cls, t) for t in tiers
                 if ('i_tod_card2_art_tier_%s_%d' % (cls, t)) in inst]
        if parts:
            L.append('        %s = { %s },' % (cls, ', '.join(parts)))
    L.append('    },')
    if classes:
        # the classes drawn as LAYERED cards (every card they can be dealt has its art)
        L.append('    classes = { %s },' % ', '.join('%s = true' % c for c in sorted(classes)))
    L.append('}')
    return '\n'.join(L) + '\n'


def zone_block(installed):
    lines = [ZBEGIN, 'rawfile,' + MANIFEST_REL]
    lines += ['image,' + n for n in sorted(installed)]
    lines.append(ZEND)
    return lines


def main():
    check = '--check' in sys.argv
    problems = []

    # 1. FX sprites (generated, deterministic)
    for name, fn in sorted(FX.items()):
        im = fn()
        p = png_path(name)
        if check:
            if not os.path.exists(p):
                problems.append('FX sprite missing: %s.png (run the installer)' % name)
            continue
        im.save(p, optimize=True)

    warnings = []
    installed = sorted(FX) + pack_present(problems, warnings)
    for wmsg in warnings:
        print('  LAYOUT WARNING: ' + wmsg)

    # 2. GDT blocks
    gdt = io.open(GDT, encoding='utf-8', newline='').read()
    have_blocks = set(re.findall(r'^\t"([a-z0-9_]+)" \( "image\.gdf" \)', gdt, re.M))
    missing_blocks = [n for n in installed if n not in have_blocks]
    if missing_blocks:
        if check:
            problems.append('GDT blocks missing: ' + ', '.join(missing_blocks))
        else:
            end = gdt.rstrip().rfind('}')
            gdt = gdt[:end] + ''.join(gdt_block(n) for n in missing_blocks) + '}\n'
            io.open(GDT, 'w', encoding='utf-8', newline='').write(gdt)

    # 3. zone block
    z = io.open(ZONE, encoding='utf-8', newline='').read()
    N = '\r\n' if '\r\n' in z else '\n'
    want = N.join(zone_block(installed))
    if ZBEGIN in z:
        a = z.index(ZBEGIN)
        b = z.index(ZEND, a) + len(ZEND)
        cur = z[a:b]
        if cur != want:
            if check:
                problems.append('zone block is stale (run the installer)')
            else:
                z = z[:a] + want + z[b:]
                io.open(ZONE, 'w', encoding='utf-8', newline='').write(z)
    else:
        if check:
            problems.append('zone block missing (run the installer)')
        else:
            z = z.rstrip(N) + N + N + want + N
            io.open(ZONE, 'w', encoding='utf-8', newline='').write(z)
    # no installed name may ALSO be zoned outside the block (double lines)
    outside = z.replace(want, '')
    for n in installed:
        if re.search(r'^image,%s\s*$' % re.escape(n), outside, re.M):
            problems.append('%s is zoned twice (outside the generated block too)' % n)

    # 4. manifest (+ which classes draw layered cards)
    classes, gaps = v2_classes(installed, problems)
    man = lua_manifest(installed, classes)
    cur = io.open(MANIFEST, encoding='utf-8').read() if os.path.exists(MANIFEST) else ''
    was = re.search(r'classes\s*=\s*\{([^}]*)\}', cur)
    for cls in (re.findall(r'([a-z_]+)\s*=\s*true', was.group(1)) if was else []):
        if cls in gaps:
            miss, tmiss = gaps[cls]
            problems.append('the %s class draws layered cards, but it can now be dealt %s with no card-v2 art%s: add the '
                            'art (ART_SLUGS / TIER_ART + i_tod_card2_art_*.png, docs/191) - the old cards and their back '
                            'are retired, nothing to fall back to (docs/217)' % (cls, ', '.join(miss) or 'no new card',
                                                              (' (and tier %s)' % '/'.join(str(t) for t in tmiss)) if tmiss else ''))
    if any(n in installed for n in V2_CORE):
        print('card_pull art: layered-card classes: %s%s' % (
            ', '.join(classes) or 'none',
            ''.join('; %s still needs %d card%s%s' % (c, len(g[0]), '' if len(g[0]) == 1 else 's',
                                                      (' + tier ' + '/'.join(str(t) for t in g[1])) if g[1] else '')
                    for c, g in sorted(gaps.items()))))
    if cur != man:
        if check:
            problems.append('TodCardArt.lua manifest is stale (run the installer)')
        else:
            io.open(MANIFEST, 'w', encoding='utf-8', newline='\n').write(man)

    pack = [n for n in installed if n not in FX]
    print('card_pull art: %d FX sprites, %d/%d art-pack images installed%s' % (
        len(FX), len(pack), len(PACK_SIZES), (' - ' + ', '.join(pack)) if pack else ''))
    if problems:
        for p in problems:
            print('  PROBLEM: ' + p)
        sys.exit(1)
    print('card_pull art: ' + ('CHECK OK' if check else 'INSTALLED'))


if __name__ == '__main__':
    main()
