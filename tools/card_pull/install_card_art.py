#!/usr/bin/env python3
"""THE PULL + CARD V2 art installer (docs/187, docs/191).

  python tools/card_pull/install_card_art.py           generate the FX sprites, install
                                                        every present card-v2 PNG
  python tools/card_pull/install_card_art.py --check   verify, write nothing (build gate)

Two kinds of image:
  FX      white, tintable sprites GENERATED here (deterministic): card glow, god rays,
          shard, ring, flash, screen-edge glow, light sweep, band pill, pip, ladder gem.
  PACK    the card-v2 layers in source_data/tod_ui_images/_images/: the card body, 4 rarity
          frames, 4 crests and the card back are GENERATED by
          tools/artgen/packs/r10_card_chrome.py (the synthwave library, its own --check gate;
          docs/217); the banner and the per-upgrade / tier illustrations are art-pack drops.
          A PACK image is installed ONLY if its PNG is present (and the right size).

TWO CARD DESIGNS, NEVER MIXED IN ONE DEAL. A layered (v2) card fills its whole
768x1152 canvas; an old baked face sat 50 px in. So card v2 is PER CLASS: a class is
listed in the manifest's `classes` (and draws EVERY card as a layered card, on the v2
back i_tod_card2_back) only when EVERY card it can be dealt has its illustration, plus
its tier 2 + tier 3 art and the core layers. Which cards a class can be dealt is READ
from the live game script (_tod_upgrades.gsc add_domain + _tod_upgrade_ui.gsc
domain_id), never copied, so a card added to a layered class without art fails --check
instead of drawing an old card after a v2 back. Every class is layered since 2026-09-29,
so the OLD back i_tod_card_back (docs/189) is RETIRED WHOLE (2026-10-05, R10 - archive/
map1_carryover/): a class that loses a card's art fails --check, it never falls back.

THE PILL (i_tod_pull_pill) is the title label and the rarity band: TodPull.lua draws it as
two LUI quads tinted rarity x 0.34 under white text. It is chamfered top-left / bottom-right
(the synthwave grammar's only corner) by PILL_CUT_V / PILL_CUT_H - LOCKSTEP with
r10_card_chrome.py, whose frames cut the header's label well to the same corner (its --check
reads this sprite back).

For every installed image this keeps three things in step, and --check proves they are:
  1. a block in source_data/tod_ui_images.gdt           (compressed high color, sRGB)
  2. an `image,` line in the zone's GENERATED block      (between the BEGIN/END markers)
  3. the GENERATED Lua manifest TodCardArt.lua           (CoD.TodCardArt: what exists)
The Lua only ever RegisterImage()s names from the manifest, so an image that is not
installed can never be asked for - a missing piece falls back to the old look instead
of drawing a white square. Never hand-edit TodCardArt.lua or the zone block.
"""
