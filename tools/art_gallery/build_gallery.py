"""build_gallery.py - THE ART ATLAS: one browsable page of every image the map ships (2026-10-04).

User 2026-10-04: "If you could create an easily navigable artifact of the current art and keep it
updated so I can always easily browse current art in game that would be great."

WHAT IT SHOWS
  in game        every image the zone packs (zone_source/zm_tod2_cybercity.zone + every *.zpkg),
                 resolved through its GDT block to the source file it is converted from
  stock / kit    zoned images whose source is not in this repo (vendored HUD kit, stock art):
                 listed by name only
  not zoned      PNGs in source_data/tod_ui_images/_images/ that no zone line packs (parked,
                 retired, masters) - on disk, NOT in the game
  in production  art/generated/<pack>/*.png - generated by tools/artgen packs, not landed yet
For each image: size, category, status, compression, the GDT and source path, the code files
that name it, the briefs (docs/*art_prompt*.md) that mention it, last change, short md5. A
change log (art/gallery/history.json, tracked) records what was added / changed / removed at
every rebuild, and the page shows it.

OUTPUT  tmp/art_gallery/site/  index.html (manifest inlined) + a/t_NN.webp (thumbnail atlases)
        + a/p_NN.webp (preview atlases) + publish_files.json (the Artifact `files` map, with
        null for atlases a previous build published that this one no longer writes)

  python tools/art_gallery/build_gallery.py          # rebuild the site + append the change log
  python tools/art_gallery/build_gallery.py --dry    # rebuild the site, do not touch history.json

Then republish (the page URL is in tools/art_gallery/README.md): the Artifact tool, publish,
file_path tmp/art_gallery/site/index.html, files = publish_files.json's map, url = that URL.
"""
import base64, csv, functools, glob, hashlib, io, json, os, re, sys, time

from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
UI_IMG = os.path.join(ROOT, 'source_data', 'tod_ui_images', '_images')
GEN = os.path.join(ROOT, 'art', 'generated')
OUT = os.path.join(ROOT, 'tmp', 'art_gallery', 'site')
HISTORY = os.path.join(ROOT, 'art', 'gallery', 'history.json')
EXCLUDE = os.path.join(ROOT, 'art', 'gallery', 'exclude.json')
TEMPLATE = os.path.join(HERE, 'index.template.html')
FONT = os.path.join(ROOT, 'fonts', 'tod_tower1.ttf')
PRIVATE = r'C:\BO3Tools\TOD2Cybercity'

THUMB = 240          # longest side of a grid thumbnail
PREVIEW = 720        # longest side of a lightbox preview
SHEET = 2048         # atlas sheet edge
PAD = 2

# (label, test) - first match wins; order is the sidebar order
