    ('Tower gauge', lambda n: n.startswith('i_tod_gauge_')),
    ('Upgrade panel', lambda n: n.startswith(('i_tod_up_', 'i_tod_upg_', 'i_tod_hint', 'i_tod_hold', 'i_tod_key', 'i_tod_frame', 'i_tod_timer', 'i_tod_tier', 'i_tod_icon'))),
    ('Class select', lambda n: n.startswith('i_tod_class')),
