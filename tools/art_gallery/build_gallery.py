def category(name):
    for label, test in CATEGORIES:
        if test(name):
            return label
    return 'Other'


def read(p):
    return open(p, encoding='utf-8', errors='replace').read()


@functools.lru_cache(maxsize=4)
def wunderfizz_image_names(root):
    """Only the exact imported machine's image identities from its source receipt."""
    receipt = os.path.join(root, 'art', 'wunderfizz', 'asset_manifest.json')
    if not os.path.isfile(receipt):
        return frozenset()
    manifest = json.loads(read(receipt))
    return frozenset(row['asset'] for row in manifest['native_definition_changes']
                     if row['kind'] == 'image' and row['field'] == 'baseImage')


def native_wunderfizz_images():
    """Include model-only textures only when this map actually packages and links them."""
    zone = os.path.join(ROOT, 'zone_source', 'zm_tod2_cybercity.zone')
    package = os.path.join(ROOT, 'zone_source', 'tod2_bo6_wunderfizz.zpkg')
    ledger = os.path.join(PRIVATE, 'usermaps', 'zm_tod2_cybercity', 'zone_source',
                          'all', 'assetinfo', 'zm_tod2_cybercity.csv')
    if (not os.path.isfile(package) or
            not re.search(r'^include,tod2_bo6_wunderfizz\s*(?://.*)?$', read(zone), re.M) or
            not os.path.isfile(ledger)):
        return {}
    with open(ledger, encoding='utf-8-sig', newline='') as stream:
        linked = {row['name'] for row in csv.DictReader(stream) if row['type'] == 'image'}
    return {name: os.path.basename(package) for name in sorted(wunderfizz_image_names(ROOT) & linked)}


def zoned_images():
    out = {}
    files = [os.path.join(ROOT, 'zone_source', 'zm_tod2_cybercity.zone')] + sorted(glob.glob(os.path.join(ROOT, 'zone_source', '*.zpkg')))
    for z in files:
        for n in re.findall(r'^image,(\S+)', read(z), re.M):
            out.setdefault(n, os.path.basename(z))
    for name, package in native_wunderfizz_images().items():
        out.setdefault(name, package)
    return out


BLOCK = re.compile(r'"([^"]+)"\s*\(\s*"image\.gdf"\s*\)\s*\{(.*?)\}', re.S)


def gdt_images():
    out = {}
    gdts = sorted(glob.glob(os.path.join(ROOT, 'source_data', '*.gdt')))
    for g in gdts:
        for name, body in BLOCK.findall(read(g)):
            m = re.search(r'"baseImage"\s+"([^"]*)"', body)
            c = re.search(r'"compressionMethod"\s+"([^"]*)"', body)
            out[name] = dict(base=m.group(1) if m else '', gdt=os.path.basename(g), comp=c.group(1) if c else '')
    return out


def resolve(rel):
    if not rel:
        return None
    rel = rel.replace('\\', '/')
    for base in (ROOT, PRIVATE):
        p = os.path.join(base, rel)
        if os.path.isfile(p):
            return p
    return None


def code_index():
    """{file: text} for every file a player-facing image name can be written in."""
    pats = ['ui/**/*.lua', 'scripts/**/*.gsc', 'scripts/**/*.csc', 'scripts/**/*.gsh']
    idx = {}
    for pat in pats:
        for p in glob.glob(os.path.join(ROOT, pat), recursive=True):
            idx[os.path.relpath(p, ROOT).replace('\\', '/')] = read(p)
    return idx


def brief_index():
    return {os.path.relpath(p, ROOT).replace('\\', '/'): read(p) for p in glob.glob(os.path.join(ROOT, 'docs', '*art_prompt*.md'))}


def fit(im, edge):
    w, h = im.size
    s = min(1.0, edge / float(max(w, h)))
    if s >= 1.0:
        return im.copy()
    return im.resize((max(1, round(w * s)), max(1, round(h * s))), Image.LANCZOS)


def pack(items, prefix):
    """Shelf-pack [(key, image)] into SHEET x SHEET sheets. -> sheets [Image], placements {key: [i,x,y,w,h]}."""
    order = sorted(items, key=lambda kv: (-kv[1].height, kv[0]))
    sheets, place = [], {}
    cur, x, y, row = None, 0, 0, 0
    used_w, used_h = 0, 0

    def new_sheet():
        return Image.new('RGBA', (SHEET, SHEET), (0, 0, 0, 0))

    sizes = []
    for key, im in order:
        w, h = im.size
        if cur is None:
            cur, x, y, row, used_w, used_h = new_sheet(), 0, 0, 0, 0, 0
        if x + w > SHEET:
            x, y, row = 0, y + row + PAD, 0
        if y + h > SHEET:
            sheets.append(cur); sizes.append((used_w, used_h))
            cur, x, y, row, used_w, used_h = new_sheet(), 0, 0, 0, 0, 0
        cur.alpha_composite(im, (x, y))
        place[key] = [len(sheets), x, y, w, h]
        used_w, used_h = max(used_w, x + w), max(used_h, y + h)
        x += w + PAD
        row = max(row, h)
    if cur is not None:
        sheets.append(cur); sizes.append((used_w, used_h))
    out = []
    for im, (uw, uh) in zip(sheets, sizes):
        out.append(im.crop((0, 0, max(4, uw), max(4, uh))))
    return out, place


def placeholder(w, h):
    return Image.new('RGBA', (max(4, w), max(4, h)), (0, 0, 0, 0))


def main():
    dry = '--dry' in sys.argv
    t0 = time.time()
    zoned = zoned_images()
    gdt = gdt_images()
    code = code_index()
    briefs = brief_index()
    entries = {}

    # 1. everything the zone packs
    for n, zfile in zoned.items():
        g = gdt.get(n)
        src = resolve(g['base']) if g else None
        if src is None and os.path.isfile(os.path.join(UI_IMG, n + '.png')):
            src = os.path.join(UI_IMG, n + '.png')
        entries[n] = dict(n=n, s='game' if src else 'stock', zone=zfile, gdt=g['gdt'] if g else '', comp=g['comp'] if g else '',
                          src=src)
    # MAP 2 ONLY (user 2026-10-04: "the artifact includes mage stuff and other stuff not even on this map ...
    # remove those"). Not shown: images no zone line packs (on-disk leftovers), zoned stock/kit images with
    # no source in the repo (no picture to show), and every image art/gallery/exclude.json names - the Mage
    # (retired whole) and the Map 1 leftovers / parked Map 1 systems the 2026-10-04 purge analysis verified
    # as unused on Map 2. Once that cleanup lands the zone itself no longer carries them.
    excl = json.load(open(EXCLUDE, encoding='utf-8')) if os.path.isfile(EXCLUDE) else {}
    for n in list(entries):
        if n in excl or entries[n]['s'] == 'stock':
            del entries[n]
    # 3. generated, not landed
    if os.path.isdir(GEN):
        for p in sorted(glob.glob(os.path.join(GEN, '*', '*.png'))):
            base = os.path.basename(p)[:-4]
            if base.startswith('_') or not base.startswith('i_'):
                continue   # review sheets and reference renders are working files, not deliverables
            if base in excl:
                continue   # a redraw of an image the Map 2 view excludes (a parked system's icon) is not upcoming art
            live = entries.get(base)
            if live and live.get('src') and open(live['src'], 'rb').read() == open(p, 'rb').read():
                continue   # already landed: the in-game copy is this exact image
            pk = os.path.basename(os.path.dirname(p))
            key = 'gen:%s/%s' % (pk, base)
            entries[key] = dict(n=base, s='prod', pack=pk, zone='', gdt='', comp='', src=p)

    thumbs, previews = [], []
    meta = []
    for key in sorted(entries, key=lambda k: (category(entries[k]['n']), entries[k]['n'], k)):
        e = entries[key]
        item = dict(k=key, n=e['n'], c=category(e['n']), s=e['s'], z=e['zone'], g=e['gdt'], cm=e['comp'])
        if e.get('pack'):
            item['pk'] = e['pack']
        src = e['src']
        if src:
            try:
                raw = open(src, 'rb').read()
                im = Image.open(io.BytesIO(raw))
                im.load()
                im = im.convert('RGBA')
                item.update(w=im.width, h=im.height, kb=round(len(raw) / 1024.0, 1),
                            m=time.strftime('%Y-%m-%d %H:%M', time.localtime(os.path.getmtime(src))),
                            md5=hashlib.md5(raw).hexdigest(), p=os.path.relpath(src, ROOT).replace('\\', '/') if src.startswith(ROOT) else src)
                thumbs.append((key, fit(im, THUMB)))
                if max(im.size) > THUMB:
                    previews.append((key, fit(im, PREVIEW)))
            except Exception as ex:  # unreadable source: list it, flag it
                item.update(err=str(ex)[:120])
        name = e['n']
        refs = [f for f, t in code.items() if name in t]
        if not refs and name.startswith('i_tod_'):
            parts = name.split('_')
            for cut in range(len(parts) - 1, 2, -1):
                pre = '_'.join(parts[:cut]) + '_'
                fam = [f for f, t in code.items() if ('"' + pre) in t]
                if fam:
                    item['fam'] = pre
                    refs = fam
                    break
        item['r'] = refs[:8]
        item['b'] = [f for f, t in briefs.items() if name in t][:6]
        meta.append(item)

    os.makedirs(os.path.join(OUT, 'a'), exist_ok=True)
    tsheets, tplace = pack(thumbs, 't')
    psheets, pplace = pack(previews, 'p')
    files = {}
    atl = {'t': [], 'p': []}
    for kind, sheets in (('t', tsheets), ('p', psheets)):
        for i, im in enumerate(sheets):
            rel = 'a/%s_%02d.webp' % (kind, i)
            im.save(os.path.join(OUT, rel), 'WEBP', quality=86 if kind == 't' else 84, method=6, alpha_quality=95)
            atl[kind].append([rel, im.width, im.height])
            files[rel] = os.path.join(OUT, rel)
    for it in meta:
        if it['k'] in tplace:
            it['t'] = tplace[it['k']]
        if it['k'] in pplace:
            it['pv'] = pplace[it['k']]

    # change log
    hist = {'last': {}, 'log': []}
    if os.path.isfile(HISTORY):
        hist = json.load(open(HISTORY, encoding='utf-8'))
    cur = {it['k']: it.get('md5', '') + '|' + it['s'] for it in meta}
    prev = hist.get('last', {})
    added = sorted(k for k in cur if k not in prev)
    removed = sorted(k for k in prev if k not in cur)
    changed = sorted(k for k in cur if k in prev and prev[k] != cur[k])
    stamp = time.strftime('%Y-%m-%d %H:%M')
    if not prev:
        entry = dict(at=stamp, first=True, total=len(cur))
    else:
        entry = dict(at=stamp, added=added, changed=changed, removed=removed)
    if (not prev) or added or changed or removed:
        hist['log'] = ([entry] + hist.get('log', []))[:60]
    hist['last'] = cur
    if not dry:
        os.makedirs(os.path.dirname(HISTORY), exist_ok=True)
        json.dump(hist, open(HISTORY, 'w', encoding='utf-8'), indent=0, sort_keys=True)

    counts = {}
    for it in meta:
        counts[it['s']] = counts.get(it['s'], 0) + 1
    manifest = dict(built=stamp, counts=counts, cats=[c for c, _ in CATEGORIES], atlases=atl, items=meta, log=hist['log'])
    html = read(TEMPLATE)
    font = base64.b64encode(open(FONT, 'rb').read()).decode('ascii')
    html = html.replace('/*__FONT__*/', font).replace('/*__MANIFEST__*/null', json.dumps(manifest, separators=(',', ':')))
    open(os.path.join(OUT, 'index.html'), 'w', encoding='utf-8').write(html)

    # the Artifact `files` map: every atlas written now, null for any a previous build published
    pub_rec = os.path.join(ROOT, 'art', 'gallery', 'published_files.json')
    old = json.load(open(pub_rec, encoding='utf-8')) if os.path.isfile(pub_rec) else []
    fmap = {k: {'from': os.path.relpath(v, ROOT).replace('\\', '/'), 'contentType': 'image/webp'} for k, v in files.items()}
    for k in old:
        if k not in fmap:
            fmap[k] = None
    json.dump(fmap, open(os.path.join(OUT, 'publish_files.json'), 'w'), indent=1)
    if not dry:
        json.dump(sorted(files), open(pub_rec, 'w'), indent=1)
    size = sum(os.path.getsize(v) for v in files.values()) + os.path.getsize(os.path.join(OUT, 'index.html'))
    print('art atlas: %d images (%s), %d thumb + %d preview atlases, %.1f MB, page %.0f KB, %.1f s'
          % (len(meta), ', '.join('%s %d' % kv for kv in sorted(counts.items())), len(tsheets), len(psheets),
             size / 1e6, os.path.getsize(os.path.join(OUT, 'index.html')) / 1024.0, time.time() - t0))
    print('change log: +%d ~%d -%d since the last build' % (len(added), len(changed), len(removed)) if prev else 'change log: first build')
    print('site:', OUT)


if __name__ == '__main__':
    main()
