    ('Pause menu', lambda n: n.startswith('i_tod_pm_')),
    ('Scoreboard', lambda n: n.startswith('i_tod_sb_')),
    # W3B 2026-10-05: the ability tile glyphs (in colour) are their own shelf; the V1 i_tod_hud_off_* keys are retired
    ('Ability icons', lambda n: n.startswith('i_tod_h2_ab_')),
    ('HUD v2', lambda n: n.startswith('i_tod_h2_')),
    ('Typeface glyphs', lambda n: re.match(r'i_tod_hud_(l[a-z]|lhyphen|lapos|ldot|lmoney|d[0-9]|dslash|dplus|ddash)$', n)),
    ('Weapon icons', lambda n: n.startswith('i_tod_hud_gun_')),
    ('Pack-a-Punch', lambda n: n.startswith('i_tod_hud_pap') or 'pap' in n.split('_')),
    ('HUD - other', lambda n: n.startswith('i_tod_hud_')),
    ('Prompt cards', lambda n: n.startswith('i_tod_prompt_')),
    ('Black Market spin', lambda n: n.startswith('i_tod_spin_')),
