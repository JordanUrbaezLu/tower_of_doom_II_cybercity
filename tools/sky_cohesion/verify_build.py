def read_log(path):
    raw = path.read_bytes()
    return raw.decode('utf-16' if raw.startswith(b'\xff\xfe') else 'utf-8-sig')


def cache_files():
    return {p.name: describe(p) for p in CACHE.glob('i_skybox_tod_cybercity_*.iwi')}


def exr_size(path):
    """Read the dataWindow only; do not decode a 400 MB panorama for a build gate."""
    def string(f):
        b = bytearray()
        while True:
            c = f.read(1)
            require(c, 'Truncated EXR header: ' + str(path))
            if c == b'\0':
                return b.decode('ascii')
            b.extend(c)
            require(len(b) < 4096, 'Invalid EXR attribute name')
    with path.open('rb') as f:
        require(f.read(4) == b'\x76\x2f\x31\x01', 'Not an EXR: ' + str(path))
        f.read(4)
        while True:
            name = string(f)
            require(name, 'EXR has no dataWindow')
            kind = string(f)
            length = struct.unpack('<I', f.read(4))[0]
            require(length < 16 * 1024 * 1024, 'Invalid EXR attribute length')
            data = f.read(length)
            require(len(data) == length, 'Truncated EXR attribute')
            if name == 'dataWindow':
                require(kind == 'box2i' and length == 16, 'Invalid EXR dataWindow')
                x0, y0, x1, y1 = struct.unpack('<iiii', data)
                return [x1 - x0 + 1, y1 - y0 + 1]


def take_snapshot(args):
    started = time.time_ns()
    stats_path = path_at(args.stats)
    stats = json.loads(stats_path.read_text(encoding='utf-8'))
    raw, mask = path_at(stats['input']), path_at(stats['sign_mask'])
    title = path_at(args.title_report) if args.title_report else raw.with_suffix('.title.json')
    master = path_at(args.master)
    require(path_at(stats['asset']) == ROOT / EXR, 'Finish stats do not describe the shipping sky EXR')
    require(stats['size'] == [8192, 4096] and exr_size(ROOT / EXR) == stats['size'], 'Shipping sky must be 8192 x 4096')
    require(exr_size(raw) == stats['size'] and exr_size(mask) == stats['size'], 'Raw/sign AOV dimensions differ from final sky')
    require(stats.get('hold_city') is True and abs(stats.get('score_city', -1) - .64) < 1e-7,
            'Finish no longer holds the city at score .64')
    require(stats.get('roll') == 0 and stats.get('mirror') is False, 'Measured sky bearing requires roll0, no mirror')
    require(math.isfinite(stats['score']) and stats['score'] > 0, 'Invalid final sky score')
    report = json.loads(title.read_text(encoding='utf-8'))
    require(report.get('version', '').startswith('cyber_monument_'), 'Title report does not describe the authored cyber monument')
    require(report.get('sign_aov') == 'sign' and report.get('lights_city') is False, 'Title AOV/light contract changed')
    require(report.get('reference_width_deg') == 65 and report.get('title_anchor_deg') == [0, 11.0], 'Title framing changed')
    source_paths = runtime_files()
    inputs = {name: describe(p) for name, p in sorted(source_paths.items())}
    authors = [ROOT / name for name in AUTHOR_FILES] + [stats_path, master, title, raw, mask]
    authors += [path_at(p) for p in args.receipt]
    authoring = {str(p): describe(p) for p in sorted(set(authors))}
    existing_cache = cache_files()
    # Refuse a moving source tree; mtimes here detect races, hashes prove content later.
    require(source_paths.keys() == runtime_files().keys(), 'Runtime file set changed while snapshotting')
    for name, p in source_paths.items():
        require(p.stat().st_mtime_ns == inputs[name]['mtime_ns'], 'Runtime source changed while snapshotting: ' + name)
    data = {'schema': 1, 'map': MAP, 'private_root': str(MT), 'started_ns': started,
            'captured_ns': time.time_ns(), 'captured_local': datetime.datetime.now().isoformat(),
            'inputs': inputs, 'authoring': authoring, 'existing_sky_cache': existing_cache,
            'stats_path': str(stats_path), 'master_path': str(master), 'title_report': str(title),
            'finish': stats, 'title': report}
    OUT.mkdir(parents=True, exist_ok=True)
    SNAP.write_text(json.dumps(data, indent=2) + '\n', encoding='utf-8')
    print('SKY INPUT SNAPSHOT:', len(inputs), 'runtime inputs,', len(authoring), 'authoring artifacts;', SNAP)


def classify_changes(before, now, ff_ns, ignored=()):
    pending = []
    for name in sorted(before.keys() | now.keys()):
        if before.get(name, {}).get('sha256') == now.get(name, {}).get('sha256'):
            continue
        if name in ignored:
            continue
        require(pathlib.PurePosixPath(name).parts[0] in SHARED, 'Owned sky input changed after snapshot: ' + name)
        require(name in now and now[name]['mtime_ns'] > ff_ns,
                'Shared-source change is not provably after the fastfile: ' + name)
        pending.append({'path': name, 'built_sha256': before.get(name, {}).get('sha256'),
                        'current_sha256': now[name]['sha256'], 'changed_ns': now[name]['mtime_ns']})
    return pending


def normalized_asset(name):
    return re.sub(r'#[0-9a-fA-F]+$', '', name)


def code_without_comments(text):
    # Keep quoted strings: a script path in a dynamic lookup is still a reference.
    return re.sub(r'''"(?:\\.|[^"\\])*"|'(?:\\.|[^'\\])*'|//[^\n]*|/\*[\s\S]*?\*/''',
                  lambda m: m[0] if m[0].startswith(('"', "'")) else '', text)


def compiled_source_roots(rows):
    """Read every packed script plus every deployed UI/zone/header source."""
    paths = set()
    packed = [normalized_asset(r['name']).replace('\\', '/') for r in rows
              if r['type'] == 'scriptparsetree']
    require(packed, 'Compiled ledger contains no scripts; cannot prove an unused peer script')
    for name in packed:
        choices = (DEP / name, MT / 'share/raw' / name, MT / name)
        p = next((p for p in choices if p.is_file()), None)
        require(p is not None, 'Packed script source unavailable: ' + name)
        paths.add(p)
    for folder in ('ui', 'zone_source'):
        paths.update(source_tree(DEP, folder).values())
    paths.update(p for p in source_tree(DEP, 'scripts').values() if p.suffix.lower() == '.gsh')
    # latin1 is intentional: old stock sources contain CP1252 comments. The
    # identifiers/directives/string paths tested here are entirely ASCII.
    return {str(p): p.read_bytes().decode('latin1') for p in sorted(paths)}


def prove_unlinked_script(name, before, current, deployed, rows, roots, ff_ns):
    require(name in UNLINKED_PEER_SCRIPTS, 'Unreviewed peer-script exception: ' + name)
    require(current['sha256'] == deployed['sha256'], 'Unlinked peer script differs between current and deployed: ' + name)
    require(current['mtime_ns'] <= ff_ns and deployed['mtime_ns'] <= ff_ns,
            'Unlinked peer script was changed or synced after the fastfile: ' + name)
    stem = name.rsplit('.', 1)[0].lower()
    # Refuse either server/client sibling and every asset type, including rawfile.
    ledger_refs = [r for r in rows if normalized_asset(r['name']).replace('\\', '/').lower().rsplit('.', 1)[0] == stem]
    require(not ledger_refs, 'Peer script or its sibling is present in compiled ledger: ' + name)
    candidate = code_without_comments((DEP / name).read_bytes().decode('latin1'))
    namespaces = re.findall(r'^\s*#namespace\s+(\w+)\s*;', candidate, re.M)
    require(len(namespaces) == 1, 'Cannot identify peer script namespace: ' + name)
    tokens = (pathlib.PurePosixPath(stem).name, namespaces[0])
    pattern = re.compile(r'(?<!\w)(?:' + '|'.join(re.escape(x) for x in tokens) + r')(?!\w)', re.I)
    referenced_by = [p for p, source in roots.items() if pattern.search(code_without_comments(source))]
    require(not referenced_by, 'Peer script is referenced by a packed script or UI/zone/header root: ' + str(referenced_by))
    inventory = '\n'.join(p + ':' + hashlib.sha256(s.encode('latin1')).hexdigest() for p, s in sorted(roots.items()))
    return {'path': name, 'snapshot_sha256': before['sha256'],
            'current_sha256': current['sha256'], 'deployed_sha256': deployed['sha256'],
            'current_mtime_ns': current['mtime_ns'], 'deployed_mtime_ns': deployed['mtime_ns'],
            'compiled_ledger_asset_matches': [], 'server_and_client_stem': stem,
            'namespace': namespaces[0], 'referenced_by': [], 'scanned_source_count': len(roots),
            'scanned_source_inventory_sha256': hashlib.sha256(inventory.encode('utf-8')).hexdigest(),
            'reason': 'Copied but unlinked peer source; absent from compiled ledger and packed script/UI/zone/header references'}


def converter_metadata():
    """Converter signature is opaque; record it, and check its source size/time."""
    db = MT / 'share/assetconvert/datasignature.db'
    with sqlite3.connect(db.as_uri() + '?mode=ro', uri=True) as con:
        rows = con.execute("SELECT name,timestamp,size,signature FROM filedata_table WHERE name LIKE '%i_skybox_tod_cybercity.exr'").fetchall()
    rows = [r for r in rows if pathlib.Path(r[0]).resolve() == (MT / EXR).resolve()]
    require(len(rows) == 1, 'Cannot uniquely identify converter metadata for the private sky EXR')
    name, stamp, size, signature = rows[0]
    source = (MT / EXR).stat()
    byte_count = int.from_bytes(size, 'little')
    source_ns = (int.from_bytes(stamp, 'little') - 116444736000000000) * 100
    require(byte_count == source.st_size and abs(source_ns - source.st_mtime_ns) <= 1000,
            'Converter metadata describes a different sky source size/time')
    return {'database': str(db), 'source': name, 'source_bytes': byte_count,
            'source_mtime_ns': source_ns, 'opaque_signature_hex': signature.hex()}


def native_bindings():
    """Prove GDT import as well as file sync; SSI names are baked, not ledger assets."""
    source = (MT / GDT).read_text(encoding='utf-8')
    checks = [('image', 'i_skybox_tod_cybercity',
               ('baseImage', 'semantic', 'compressionMethod', 'noMipMaps', 'streamable')),
              ('material', 'mtl_skybox_tod_cybercity',
               ('materialType', 'colorMap', 'skyStops', 'skyRotation'))]
    checks += [('ssi', name, ('pitch', 'yaw', 'skyboxmodel', 'stops', 'evmin', 'evmax', 'evcmp')) for name in SSIS]
    numeric = {'noMipMaps', 'streamable', 'skyStops', 'skyRotation', 'pitch', 'yaw', 'stops', 'evmin', 'evmax', 'evcmp'}
    result = {}
    db = MT / 'gdtdb/gdt.db'
    with sqlite3.connect(db.as_uri() + '?mode=ro', uri=True) as con:
        # The legacy database contains schema constructs unsupported by modern
        # SQLite. This connection-only flag permits reading; mode=ro forbids writes.
        con.execute('pragma writable_schema=ON')
        con.row_factory = sqlite3.Row
        for kind, name, keys in checks:
            block = re.search(r'"' + re.escape(name) + r'"\s*\(\s*"' + kind + r'\.gdf"\s*\)\s*\{(.*?)\n\t\}', source, re.S)
            require(block is not None, 'Sky GDT block missing: ' + name)
            fields = dict(re.findall(r'"([^"\n]+)"\s+"([^"\n]*)"', block[1]))
            row = con.execute('SELECT * FROM ' + kind + ' WHERE _name=?', (name,)).fetchone()
            require(row is not None, 'Native GDT database asset missing: ' + name)
            for key in keys:
                want, got = fields[key], row[key]
                if key in numeric:
                    same = math.isclose(float(want), float(got), rel_tol=0, abs_tol=1e-6)
                else:
                    same = re.sub(r'\\+', '/', str(want)) == re.sub(r'\\+', '/', str(got))
                require(same, 'Native database binding differs from GDT: ' + name + '.' + key)
            result[name] = {key: row[key] for key in keys}
    return result


def verify(args):
    saved = json.loads(SNAP.read_text(encoding='utf-8'))
    require(saved['schema'] == 1 and saved['map'] == MAP and saved['private_root'] == str(MT), 'Unexpected snapshot identity')
    captured = saved['captured_ns']
    log = path_at(args.build_log)
    text = read_log(log)
    require('[build] === BUILD OK ===' in text and '[build] mode = FULL geometry' in text, 'A successful guarded FULL build is required')
    require('[build] === Radiant LED (lighting recompute) ===' in text and '[build] fresh LED:' in text,
            'Changed sky requires a fresh Radiant LED bake; reused/omitted LED is insufficient')
    ff = DEP / 'zone' / (MAP + '.ff')
    ff_info = describe(ff)
    ff_ns = ff_info['mtime_ns']
    require(ff_ns > captured, 'Fastfile predates source snapshot')
    require(ff_ns <= log.stat().st_mtime_ns <= ff_ns + 1800 * 10**9, 'Build log does not match the deployed fastfile interval')
    ledger = DEP / 'zone_source/all/assetinfo' / (MAP + '.csv')
    require(captured < ledger.stat().st_mtime_ns <= ff_ns + 5 * 10**9, 'Asset ledger is not from this build')
    with ledger.open(encoding='utf-8-sig', newline='') as f:
        rows = list(csv.DictReader(f))
    inputs = saved['inputs']
    now = {name: describe(p) for name, p in runtime_files().items()}
    deployed = {name: describe(target(name)) for name in inputs}
    ignored = {}
    for name in UNLINKED_PEER_SCRIPTS & inputs.keys() & now.keys():
        if (now[name]['sha256'] != inputs[name]['sha256'] and
                deployed[name]['sha256'] != inputs[name]['sha256']):
            ignored[name] = prove_unlinked_script(name, inputs[name], now[name], deployed[name],
                                                  rows, compiled_source_roots(rows), ff_ns)
    pending = classify_changes(inputs, now, ff_ns, ignored)
    for name, expected in inputs.items():
        dst = deployed[name]
        require(name in ignored or dst['sha256'] == expected['sha256'], 'Deployed input differs from snapshot: ' + name)
        require(dst['mtime_ns'] <= ff_ns, 'Deployed input newer than fastfile: ' + name)
    for folder in SHARED:
        expected = {p for p in inputs if p.startswith(folder + '/')}
        require(set(source_tree(DEP, folder)) == expected, 'Deployed script/UI/zone file set differs: ' + folder)
    for name, expected in saved['authoring'].items():
        require(describe(pathlib.Path(name))['sha256'] == expected['sha256'], 'Authoring artifact changed after snapshot: ' + name)

    bake = {}
    for suffix in ('d3dbsp', 'led'):
        p = RAW_MAP / (MAP + '.' + suffix)
        info = describe(p)
        require(captured < info['mtime_ns'] <= ff_ns and info['bytes'] > 1024**2, 'Missing/stale bake: ' + str(p))
        bake[suffix] = info
    led = (RAW_MAP / (MAP + '.led')).read_bytes()
    # LED strings carry a uint32 byte length, not a null terminator.
    require(all(struct.pack('<I', len(name)) + name.encode() in led for name in SSIS),
            'Fresh LED does not contain both length-prefixed map SSI names')
    # geom_key records the bytes Radiant actually consumed, including the EXR,
    # the complete sky GDT, and the exact resulting LED/BSP hashes.
    geom_path = RAW_MAP / (MAP + '.geomkey.json')
    geom = json.loads(geom_path.read_text(encoding='utf-8'))
    require(geom.get('version') == 'geom-key-2' and geom.get('map') == MAP, 'Unknown geometry bake record')
    parts = {k.replace('\\', '/'): v for k, v in geom['parts'].items()}
    for name, kind in ((EXR, 'file'), (GDT, 'gdt'), (MAP_SOURCE, 'map')):
        require(parts.get(kind + ':' + name) == digest(target(name), 'sha1'), 'Bake record did not consume current bytes: ' + name)
    for suffix in ('d3dbsp', 'led'):
        name = MAP + '.' + suffix
        require(geom['outputs'].get(name) == digest(RAW_MAP / name, 'sha1'), 'Compiled output differs from bake record: ' + name)
    require(captured < geom_path.stat().st_mtime_ns <= ff_ns, 'Geometry bake receipt is stale')

    assets = {(r['type'], normalized_asset(r['name'])) for r in rows}
    needed = {('image', 'i_skybox_tod_cybercity'), ('material', 'mc/mtl_skybox_tod_cybercity'),
              ('techset', 'mc/sky_latlong_hdr'), ('xmodel', 'skybox_tod_cybercity')}
    needed.update(('fx', 'tod/jump/fx_jt_' + n) for n in FX_NAMES)
    needed.add(('xmodel', 'tod_jt_sign_lit'))
    require(needed <= assets, 'Native sky/jump assets missing from ledger: ' + str(sorted(needed - assets)))
    native_rows = [r for r in rows if (r['type'], normalized_asset(r['name'])) in needed]

    current_cache = cache_files()
    changed_cache = {n: v for n, v in current_cache.items()
                     if v['sha256'] != saved['existing_sky_cache'].get(n, {}).get('sha256')}
    require(len(changed_cache) == 1, 'Expected exactly one fresh content-hash sky .iwi; found ' + str(list(changed_cache)))
    cache_name, compiled = next(iter(changed_cache.items()))
    require(captured < compiled['mtime_ns'] <= ff_ns and compiled['bytes'] > 1024**2,
            'Compiled sky image is outside this build interval')
    metadata = converter_metadata()
    bindings = native_bindings()
    result = {'verified_at': datetime.datetime.now().isoformat(), 'snapshot': str(SNAP),
              'snapshot_sha256': digest(SNAP), 'build_log': str(log), 'build_log_sha256': digest(log),
              'ff': ff_info, 'native_bake': bake, 'geometry_record_sha256': digest(geom_path),
              'geometry_key': geom['key'], 'checked_runtime_inputs': len(inputs),
              'matched_runtime_inputs': len(inputs) - len(ignored),
              'matched_authoring_artifacts': len(saved['authoring']), 'asset_ledger_sha256': digest(ledger),
              'native_assets': native_rows, 'ssi_names_in_fresh_led': list(SSIS),
              'native_gdt_bindings': bindings,
              'compiled_sky': {'path': str(CACHE / cache_name), **compiled}, 'converter': metadata,
              'deployed_inputs_match_snapshot': not ignored, 'inputs_not_newer_than_ff': True,
              'owned_sky_inputs_match_current': True, 'current_source_parity': not pending and not ignored,
              'linked_source_snapshot_parity': not pending,
              'copied_sources_match_current': all(name in now and value['sha256'] == now[name]['sha256']
                                                  for name, value in deployed.items()) and now.keys() == inputs.keys(),
              'ignored_unlinked_source_changes': list(ignored.values()),
              'pending_source_changes': pending,
              'status': ('built_with_later_source_changes' if pending else
                         'built_with_unlinked_peer_changes' if ignored else 'built_for_user_test'),
              'game_launched': False, 'native_visual_verified': False}
    (OUT / 'build.json').write_text(json.dumps(result, indent=2) + '\n', encoding='utf-8')
    print('SKY BUILD ART VERIFIED:', len(inputs) - len(ignored), 'snapshot-matched runtime inputs;',
          len(needed), 'packed assets;', cache_name)
    if ignored:
        print('COPIED BUT NOT LINKED; snapshot/current_source_parity=false:', ', '.join(ignored))
    if pending:
        print('LATER WORK NOT INCLUDED; current_source_parity=false:', ', '.join(p['path'] for p in pending))
        require(args.record_built_art, 'Current shared sources differ; earlier art build recorded, current checkout is not build-verified')
    elif not ignored:
        print('CURRENT SOURCE PARITY OK; fresh sky/probe bake proven; native visuals unplayed')
    else:
        print('LINKED SOURCE SNAPSHOT PARITY OK; fresh sky/probe bake proven; native visuals unplayed')


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    action = ap.add_mutually_exclusive_group(required=True)
    action.add_argument('--snapshot', action='store_true')
    action.add_argument('--build-log')
    ap.add_argument('--stats', default='docs/sky_preview/sky3d_stats.json')
    ap.add_argument('--master', default='art/sky3d/tod2_sky.blend')
    ap.add_argument('--title-report', help='Defaults to <raw from final stats>.title.json')
    ap.add_argument('--receipt', action='append', default=[], help='Additional retained final-render receipt to hash')
    ap.add_argument('--record-built-art', action='store_true', help='Explicitly record proven earlier art with later unsynced peer edits; never claim current source parity')
    args = ap.parse_args()
    try:
        take_snapshot(args) if args.snapshot else verify(args)
    except (ValueError, OSError, KeyError, TypeError, sqlite3.Error, struct.error) as exc:
        print('SKY BUILD VERIFY FAILED:', exc, file=sys.stderr)
        return 1
    return 0


