function read(rel) {
  return fs.readFileSync(path.join(ROOT, rel), 'utf8').replace(/\r\n/g, '\n');
}

function define(text, name, file) {
  const m = text.match(new RegExp('^#define\\s+' + name + '\\s+(.+?)\\s*(?://.*)?$', 'm'));
  if (!m) throw new Error(`${file}: #define ${name} not found`);
  return m[1].trim();
}

function num(text, name, file) {
  const raw = define(text, name, file).replace(/^\(\s*(.*?)\s*\)$/, '$1');
  const n = Number(raw);
  if (!Number.isFinite(n)) throw new Error(`${file}: #define ${name} is not a number (${raw})`);
  return n;
}

function vec(text, name, file) {
  const raw = define(text, name, file);
  const m = raw.match(/^\(\s*(-?[\d.]+)\s*,\s*(-?[\d.]+)\s*,\s*(-?[\d.]+)\s*\)$/);
  if (!m) throw new Error(`${file}: #define ${name} is not a vector (${raw})`);
  return [Number(m[1]), Number(m[2]), Number(m[3])];
}

function gscReturnVec(text, fn, file) {
  const m = text.match(new RegExp('function ' + fn + '\\(\\)\\s*\\{\\s*return \\(\\s*(-?[\\d.]+),\\s*(-?[\\d.]+),\\s*(-?[\\d.]+)\\s*\\);'));
  if (!m) throw new Error(`${file}: function ${fn}() returning a vector not found`);
  return [Number(m[1]), Number(m[2]), Number(m[3])];
}

function gscReturnNum(text, fn, file) {
  const m = text.match(new RegExp('function ' + fn + '\\(\\)\\s*\\{\\s*return (-?[\\d.]+);'));
  if (!m) throw new Error(`${file}: function ${fn}() returning a number not found`);
  return Number(m[1]);
}

// A generated effect's element: -> { life: [ms, ms], alpha: [[f, a], ...] } (its first alpha curve).
function efxElement(rel, name) {
  const text = read(rel);
  const start = text.indexOf('\tname "' + name + '";');
  if (start < 0) throw new Error(`${rel}: element ${name} not found`);
  const end = text.indexOf('\n}\n', start);
  const body = text.slice(start, end < 0 ? undefined : end);
  const life = body.match(/\n\tlifeSpanMsec (-?[\d.]+) (-?[\d.]+);/);
  const ag = body.match(/\n\talphaGraph [-\d.]+\n\t\{\n\t\t\{\n([\s\S]*?)\n\t\t\}/);
  if (!life || !ag) throw new Error(`${rel}: ${name} has no lifeSpanMsec / alphaGraph`);
  const alpha = ag[1].trim().split('\n').map((l) => l.trim().split(/\s+/).map(Number));
  return { life: [Number(life[1]), Number(life[2])], alpha };
}

function luaNum(text, name, file) {
  const m = text.match(new RegExp('^local ' + name + '\\s*=\\s*(-?[\\d.]+)', 'm'));
  if (!m) throw new Error(`${file}: local ${name} not found`);
  return Number(m[1]);
}

// THE CAMERA PATH (the second pass, 2026-09-30): _tod_jumppad.gsc's cine_cam_plan / cine_cam_angles, RUN. -> a
// function (view, flightYaw) -> (t -> { pitch, yaw }) for a rider who launched looking at `view` ({ pitch, yaw }).
const angleClamp180 = (a) => { let r = ((a % 360) + 360) % 360; if (r > 180) r -= 360; return r; };
function cameraOf(jp) {
  const defines = Object.fromEntries([...jp.matchAll(/^#define (\w+)\s+\(?\s*(-?[\d.]+)\s*\)?/gm)].map(m => [m[1], Number(m[2])]));
  const g = gscLoad([['tod_jumppad', jp]], defines, { builtins: { AngleClamp180: angleClamp180 } });
  return (view, flightYaw) => {
    const plan = g.call('cine_cam_plan', [V(view.pitch, view.yaw, 0), flightYaw]);
    const at = (t) => { const a = g.call('cine_cam_angles', [plan, t]); return { pitch: a[0], yaw: a[1] }; };
    at.plan = plan;
    return at;
  };
}

function load() {
  const jp = read(FILES.jumppad), jt = read(FILES.title), crown = read(FILES.crown), cine = read(FILES.cine);
  const city = read(FILES.city), fx = read(FILES.fx);
  const P = (name) => num(jp, 'TOD_JUMPPAD_' + name, FILES.jumppad);
  const T = (name) => num(jt, 'TOD_JT_' + name, FILES.title);
  const TV = (name) => vec(jt, 'TOD_JT_' + name, FILES.title);

  // the flight + camera (scene_geometry.js's J)
  const J = {
    CINE_SECS: P('CINE_SECS'), APEX: P('APEX'), TURN_AT: P('CINE_TURN_AT'), TURN_SECS: P('CINE_TURN_SECS'),
    PITCH_SECS: P('CINE_PITCH_SECS'), HOLD_SECS: P('CINE_HOLD_SECS'), BACK_SECS: P('CINE_BACK_SECS'),
    LAND_PITCH: P('CINE_LAND_PITCH'),
    SIGN_YAW: P('CINE_SIGN_YAW'), SIGN_PITCH: P('CINE_SIGN_PITCH'), DRIFT_YAW: P('CINE_DRIFT_YAW'),
    DRIFT_PITCH: P('CINE_DRIFT_PITCH'),
    DWELL: P('CINE_DWELL'), DWELL_AT: P('CINE_DWELL_AT'), DWELL_SPAN: P('CINE_DWELL_SPAN'),
    W: { A: P('WARP_A'), B: P('WARP_B'), C: P('WARP_C'), D: P('WARP_D'), L: P('WARP_L') },
  };
  J.SETTLE = J.TURN_AT + J.TURN_SECS;
  J.SWING_BACK = J.SETTLE + J.HOLD_SECS;
  // the server's beats (absolute seconds from the launch)
  const BEATS = { START: 0, SHIPS: P('CINE_SHIPS_AT'), IMPACT: P('CINE_IMPACT_AT'), IGNITE: P('CINE_IGNITE_AT'), END: J.SWING_BACK };
  // the client's scene
  const S = {
    CRASH: TV('CRASH'), DIVE: T('DIVE'), BOW: T('BOW'), RUN: T('RUN'), RUN_SECS: T('RUN_SECS'), BOB: T('BOB'),
    WARP_A: T('WARP_A'), WARP_B: T('WARP_B'), UNDER_WHITE: T('UNDER_WHITE'), WRECK_A: TV('WRECK_A'), WRECK_B: TV('WRECK_B'),
    REVEAL: T('REVEAL'), RUN_ACCEL: T('RUN_ACCEL'), BOB_SECS: T('BOB_SECS'),
    SIGN_YAW: T('SIGN_YAW'), SIGN_EL: T('SIGN_EL'), SIGN_DIST: T('SIGN_DIST'), HOST_LINGER: T('HOST_LINGER'),
    WATCHDOG: T('WATCHDOG'), LOG: T('LOG'), SIGN_MODEL: define(jt, 'TOD_JT_SIGN_MODEL', FILES.title).replace(/^"|"$/g, ''),
  };
  // THE FLICKER (the client's own table: on / off ms pairs, then steady on)
  const fl = jt.match(/function flicker_ms\(\)\s*\{\s*return array\(([^)]*)\);/);
  if (!fl) throw new Error(FILES.title + ': flicker_ms() not found');
  S.FLICKER_MS = fl[1].split(',').map(v => Number(v.trim()));
  if (!S.FLICKER_MS.length || S.FLICKER_MS.length % 2 || S.FLICKER_MS.some(v => !(v > 0))) throw new Error(FILES.title + ': flicker_ms() must be on/off pairs of positive ms');
  S.FLICKER_SECS = S.FLICKER_MS.reduce((a, b) => a + b, 0) / 1000;
  // the white-out (ms)
  const FLASH = { IN: luaNum(cine, 'FLASH_IN_MS', FILES.cine), HOLD: luaNum(cine, 'FLASH_HOLD_MS', FILES.cine),
                  OUT: luaNum(cine, 'FLASH_OUT_MS', FILES.cine) };
  // the pad and the landing spots (GENERATED)
  const PAD = gscReturnVec(crown, 'jumppad_launch_org', FILES.crown);
  const PAD_R = gscReturnNum(crown, 'jumppad_trigger_r', FILES.crown);
  const block = crown.match(/function jumppad_land_orgs\(\)\s*\{([\s\S]*?)return a;/);
  if (!block) throw new Error(FILES.crown + ': jumppad_land_orgs() not found');
  const SPOTS = [...block[1].matchAll(/\(\s*(-?[\d.]+),\s*(-?[\d.]+),\s*(-?[\d.]+)\s*\)/g)].map(m => m.slice(1, 4).map(Number));
  // the gunship
  const man = JSON.parse(read(FILES.manifest));
  const gun = man.ships.find(s => s.ship === 'gunship');
  if (!gun) throw new Error(FILES.manifest + ': no gunship');
  const GUN = { lo: gun.bounds[0], hi: gun.bounds[1], models: gun.models };
  // the sky sign's elevation (the authored cyber monument) and the glows' layout distance (gen_fx.py)
  const gate = city.match(/^GATE = dict\(([\s\S]*?)\n\s*sat=/m);
  if (!gate) throw new Error(FILES.city + ': GATE block not found');
  const boxEl = gate[1].match(/\bbox_el=([\d.]+)/);
  if (!boxEl) throw new Error(FILES.city + ': GATE box_el not found');
  const fxDist = fx.match(/^SIGN_DIST = (\d+)/m);
  if (!fxDist) throw new Error(FILES.fx + ': SIGN_DIST not found');
  const fxNum = (name) => {
    const m = fx.match(new RegExp('^' + name + ' = ([\\d.]+)', 'm'));
    if (!m) throw new Error(FILES.fx + ': ' + name + ' not found');
    return Number(m[1]);
  };
  const ringEyes = fx.match(/^RING_AT, EYES_AT = ([\d.]+), ([\d.]+)/m);
  if (!ringEyes) throw new Error(FILES.fx + ': RING_AT / EYES_AT not found');
  // the generated effects are the truth that ships: their lives and alpha curves, read from the .efx
  const blaze = efxElement(FILES.fxDir + '/fx_jt_blaze.efx', 'jz_title');
  const ring = efxElement(FILES.fxDir + '/fx_jt_blaze.efx', 'jz_ring');
  const eye = efxElement(FILES.fxDir + '/fx_jt_blaze.efx', 'jz_eye_l');
  const FX = {
    REVEAL: fxNum('REVEAL'), RING_AT: Number(ringEyes[1]), EYES_AT: Number(ringEyes[2]),
    BLAZE_LIFE: blaze.life[0], BLAZE_CURVE: blaze.alpha, RING_CURVE: ring.alpha, EYE_CURVE: eye.alpha,
  };
  // THE LIT SIGN CARD (GENERATED receipt + GDT): the model the client shows at the reveal
  const CARD = fs.existsSync(path.join(ROOT, FILES.card)) ? JSON.parse(read(FILES.card)) : null;
  const CARD_GDT = fs.existsSync(path.join(ROOT, FILES.cardGdt)) ? read(FILES.cardGdt) : '';
  return { J, BEATS, S, FLASH, PAD, PAD_R, SPOTS, GUN, FX, CARD, CARD_GDT, SIGN_BOX_EL: Number(boxEl[1]), FX_SIGN_DIST: Number(fxDist[1]),
           cam: cameraOf(jp), text: { jp, jt, cine }, FILES, ROOT };
}

module.exports = { load, read, define, num, vec, ROOT, FILES };
